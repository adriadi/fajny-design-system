// Builds docs/button-preview.html: every Button variant in every state, on a light and a dark
// surface, from tokens/css/tokens.css and components/button.css. It's the Button's preview on the
// design system page and a page to open locally. Generated: don't edit, rebuild.
//
// Hover, active and focus can't be shown at rest, so the preview copies those rules onto
// data-preview attributes. The copies come from button.css itself, so the preview can't drift.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const OUT = 'docs/button-preview.html';
const tokens = readFileSync('tokens/css/tokens.css', 'utf8').replace(/^\/\*\*[\s\S]*?\*\/\s*/, '');
const button = readFileSync('components/button.css', 'utf8');

const forced = button
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .match(/[^{}]+\{[^{}]*\}/g)
  .filter((rule) => /:hover|:focus-visible/.test(rule))
  .map((rule) => rule.trim()
    .replace(/:is\(:hover, :active\)/g, '[data-preview="hover"]')
    .replace(/:focus-visible/g, '[data-preview="focus"]'))
  .join('\n');

const VARIANTS = [
  ['primary', 'Primary', 'View my work'],
  ['secondary', 'Secondary', 'Download CV'],
  ['link', 'Link', 'Case studies'],
  ['primary fds-button--nav', 'Navigation', "Let's talk"],
];
const STATES = [
  ['default', ''],
  ['hover', ' data-preview="hover"'],
  ['focus', ' data-preview="focus"'],
  ['active', ' data-preview="hover"'],
  ['disabled', ' aria-disabled="true"'],
  ['loading', ' aria-disabled="true" data-loading'],
];

const cell = ([cls, , label], [state, attrs]) => {
  if (cls === 'link' && (state === 'disabled' || state === 'loading')) return '<td class="na">n/a</td>';
  const text = state === 'loading' ? 'Sending…' : label;
  return `<td><button type="button" class="fds-button fds-button--${cls}"${attrs}>${text}</button></td>`;
};
const table = (surface) => `
  <section class="panel${surface === 'dark' ? ' fds-surface-dark' : ''}">
    <h2>${surface === 'dark' ? 'Dark surface' : 'Light surface'}</h2>
    <table>
      <thead><tr><th></th>${STATES.map(([s]) => `<th>${s}</th>`).join('')}</tr></thead>
      <tbody>
${VARIANTS.map((v) => `        <tr><th>${v[1]}</th>${STATES.map((s) => cell(v, s)).join('')}</tr>`).join('\n')}
      </tbody>
    </table>
  </section>`;

const html = `<!-- @dsCard group="Components" height=620 width=1100 subtitle="Primary, secondary and link, every state, on light and dark" -->
<!-- Generated by scripts/build-button-preview.js from tokens/css/tokens.css and components/button.css: don't edit, rebuild. -->
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Button</title>
<style>
${tokens}
/* The preview uses the uploaded Inter of the design system page when it's there. */
:root { --fds-font-typeface-inter: "Inter Variable Font opsz,wght", Inter, system-ui, sans-serif; }
${button}
/* Preview only: hover, active and focus shown at rest. */
${forced}
/* Preview layout */
body { margin: 0; background: var(--fds-color-background); font-family: var(--fds-font-family-small); }
.panel { box-sizing: border-box; width: max-content; min-width: 100%; padding: var(--fds-space-6); background: var(--fds-color-background); color: var(--fds-color-text); }
.panel.fds-surface-dark { background: var(--fds-color-surface-dark); }
.panel h2 { margin: 0 0 var(--fds-space-4); font: var(--fds-font-weight-overline) var(--fds-font-size-overline)/var(--fds-font-line-height-overline) var(--fds-font-family-overline); letter-spacing: var(--fds-font-letter-spacing-overline); text-transform: uppercase; }
table { border-collapse: separate; border-spacing: var(--fds-space-4) var(--fds-space-3); margin: 0 calc(-1 * var(--fds-space-4)); }
th { text-align: left; font-size: var(--fds-font-size-small); font-weight: var(--fds-font-weight-small); color: var(--fds-color-text-muted); }
td.na { font-size: var(--fds-font-size-small); color: var(--fds-color-text-muted); }
</style>
</head>
<body>
${table('light')}
${table('dark')}
</body>
</html>
`;

mkdirSync('docs', { recursive: true });
writeFileSync(OUT, html);
console.log(`✔︎ ${OUT}: ${VARIANTS.length} variants × ${STATES.length} states on light and dark.`);
