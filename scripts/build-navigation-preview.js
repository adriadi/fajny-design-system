// Builds docs/navigation-preview.html: the full navigation (wide, with the current-page underline, and on
// a dark surface), the collapsed one with its drawer closed and open (the closed one works: try it, with
// the keyboard too) and the minimal bar. From tokens/css/tokens.css, components/button.css,
// components/navigation.css and components/navigation.js. It's the Navigation's preview on the design
// system page and a page to open locally. Generated: don't edit, rebuild.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const OUT = 'docs/navigation-preview.html';
const tokens = readFileSync('tokens/css/tokens.css', 'utf8').replace(/^\/\*\*[\s\S]*?\*\/\s*/, '');
const button = readFileSync('components/button.css', 'utf8');
const nav = readFileSync('components/navigation.css', 'utf8');
const script = readFileSync('components/navigation.js', 'utf8');

const LINKS = [['Work', '#work', true], ['About', '#about'], ['Journal', '#journal']];
let n = 0;
// current: the link that is the current page; state: classes the script would set, for the static drawer.
const full = ({ classes = '', state = '', open = false, current = true } = {}) => {
  const id = `menu-${++n}`;
  const links = LINKS.map(([label, href, isCurrent]) =>
    `<li><a class="fds-button fds-button--link fds-nav__link" href="${href}"${current && isCurrent ? ' aria-current="page"' : ''}>${label}</a></li>`).join('\n        ');
  return `<nav class="fds-nav${state}${classes}" aria-label="Main">
      <a class="fds-nav__brand" href="#top">Brand name</a>
      <button class="fds-nav__toggle" type="button" aria-expanded="${open}" aria-controls="${id}" aria-label="Menu"><span class="fds-nav__bars" aria-hidden="true"></span></button>
      <div class="fds-nav__menu" id="${id}">
        <ul class="fds-nav__list">
        ${links}
        <li><a class="fds-button fds-button--primary fds-button--nav" href="#contact">Contact</a></li>
        </ul>
      </div>
    </nav>`;
};
const minimal = () => `<nav class="fds-nav fds-nav--minimal" aria-label="Case study">
      <span class="fds-nav__brand">Brand name</span>
      <a class="fds-button fds-button--link fds-nav__link fds-nav__back" href="#top"><span aria-hidden="true">←</span> All work</a>
    </nav>`;

const frame = (note, inner, cls = '') => `
    <p class="note">${note}</p>
    <div class="frame${cls}">
    ${inner}
    </div>`;

const html = `<!-- @dsCard group="Components" height=900 width=1200 subtitle="The full navigation, its drawer closed and open, the current-page underline, a dark surface and the minimal bar" -->
<!-- Generated by scripts/build-navigation-preview.js from tokens/css/tokens.css and components/*: don't edit, rebuild. -->
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Navigation</title>
<style>
${tokens}
/* The preview uses the uploaded Inter of the design system page when it's there. */
:root { --fds-font-typeface-inter: "Inter Variable Font opsz,wght", Inter, system-ui, sans-serif; }
${button}
${nav}
/* Preview layout: the bars sit in frames instead of sticking to the top of the page. */
body { margin: 0; background: var(--fds-color-background); color: var(--fds-color-text); font-family: var(--fds-font-family-small); }
.panel { padding: var(--fds-space-8) var(--fds-space-6); }
.panel h2 { margin: 0 0 var(--fds-space-4); font: var(--fds-font-weight-overline) var(--fds-font-size-overline)/var(--fds-font-line-height-overline) var(--fds-font-family-overline); letter-spacing: var(--fds-font-letter-spacing-overline); text-transform: uppercase; }
.panel .note { margin: var(--fds-space-6) 0 var(--fds-space-3); font-size: var(--fds-font-size-small); font-weight: var(--fds-font-weight-small); color: var(--fds-color-text-muted); }
.frame { position: relative; max-width: calc(var(--fds-space-30) * 8); border: var(--fds-border-width-default) solid var(--fds-color-border); background: var(--fds-color-surface-subtle); }
.frame.phone { width: calc(var(--fds-space-30) * 3 + var(--fds-space-10)); max-width: 100%; min-height: calc(var(--fds-space-30) * 3); }
.frame .fds-nav { position: relative; }
</style>
</head>
<body id="top">
  <section class="panel">
    <h2>Full navigation</h2>${frame('The current page has the gold underline and aria-current="page"; Contact is a Button', full())}${frame('On a dark surface: the roles switch by themselves, and the underline stays gold', full({ classes: ' fds-surface-dark' }))}
  </section>
  <section class="panel">
    <h2>Collapsed: the links don't fit</h2>${frame('Closed: the drawer is hidden and out of the tab order. Press the menu button, then try Tab, Shift+Tab and Escape', full(), ' phone')}${frame('Open: the same bar with its drawer open (shown as it looks; the interactive one is above)', full({ state: ' fds-nav--ready fds-nav--collapsed fds-nav--open', open: true }), ' phone')}
  </section>
  <section class="panel">
    <h2>Minimal</h2>${frame('A brand name and a back link: the case-study bar. No menu, no drawer', minimal())}
  </section>
<script>
${script}
</script>
</body>
</html>
`;

mkdirSync('docs', { recursive: true });
writeFileSync(OUT, html);
console.log(`✔︎ ${OUT}: full, dark, collapsed (closed and open) and minimal.`);
