// Builds docs/highlight-preview.html: the light Highlight (a quote, a cited statistic, an insight with an icon)
// and the dark one on the page background, a subtle surface and a dark surface, and both inside an article
// that has its own heading and paragraph rules, to show the spacing holds. From tokens/css/tokens.css and
// components/highlight.css. It's the Highlight's preview on the design system page and a page to open
// locally. Generated: don't edit, rebuild.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const OUT = 'docs/highlight-preview.html';
const tokens = readFileSync('tokens/css/tokens.css', 'utf8').replace(/^\/\*\*[\s\S]*?\*\/\s*/, '');
const highlight = readFileSync('components/highlight.css', 'utf8');

const ICON = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><path d="M21 12a9 9 0 1 1-3-6.7"/><path d="M21 4v5h-5"/></svg>';

const quote = '<figure class="fds-highlight">\n      <div class="fds-highlight__body">\n        <blockquote class="fds-highlight__quote">“Nothing ships unless the person it is for can understand it on day one.”</blockquote>\n        <figcaption class="fds-highlight__cite">Name · Role, Organisation</figcaption>\n      </div>\n    </figure>';
const statistic = '<figure class="fds-highlight">\n      <div class="fds-highlight__body">\n        <blockquote class="fds-highlight__quote">Nine in ten of the people we asked said the same thing.</blockquote>\n        <figcaption class="fds-highlight__cite">Example survey · 2024 · Example organisation</figcaption>\n      </div>\n    </figure>';
const insight = `<aside class="fds-highlight">\n      <span class="fds-highlight__icon" aria-hidden="true">${ICON}</span>\n      <div class="fds-highlight__body">\n        <p class="fds-highlight__quote">Changes showed up on both devices at once, with no refresh and no waiting.</p>\n      </div>\n    </aside>`;
const dark = '<div class="fds-highlight fds-highlight--dark">\n      <p class="fds-highlight__label">The core gap</p>\n      <h3 class="fds-highlight__title">One sentence that states it.</h3>\n      <p class="fds-highlight__text">One or two short paragraphs that say what follows from it.</p>\n      <p class="fds-highlight__text">A second paragraph sits 12px under the first.</p>\n    </div>';

// The same quote with its text in a <p>, which the article's paragraph rule would reach.
const quoteInP = quote.replace('<blockquote', '<p').replace('</blockquote>', '</p>');
const note = (t) => `\n    <p class="note">${t}</p>`;
const light = (surface) => note('Light: a quote with its source, no icon')
  + `\n    ${quote}` + note('Light: a cited statistic') + `\n    ${statistic}` + note('Light with the icon slot: an insight, no source') + `\n    ${insight}`;

const panel = ([name, cls]) => {
  const onDark = cls.includes('dark');
  return `
  <section class="panel${cls}">
    <h2>${name}</h2>${light()}${onDark ? note('The light variant stays light on a dark surface; the dark variant is the same navy, so it is shown on the light surfaces') : note('Dark: a label, a heading and two paragraphs; the label sits 16px above the heading') + `\n    ${dark}`}
  </section>`;
};

const SURFACES = [['Page background', ''], ['Subtle surface', ' subtle'], ['Dark surface', ' fds-surface-dark']];

const article = `
  <section class="panel">
    <h2>In an article with its own rules</h2>${note('The article styles its own h3 (40px above) and p (20px below), as a case study page does. The blocks keep their own spacing: the label is 16px above the heading, the source is 12px under the quote')}
    <div class="article">
      <p>A paragraph of the article, with the article's own spacing under it.</p>
      ${quoteInP}
      <p>Another paragraph. The quote above has its source 12px under it, not 20px.</p>
      ${dark}
      <p>The end of the article.</p>
    </div>
  </section>`;

const html = `<!-- @dsCard group="Components" height=900 width=1200 subtitle="The light Highlight (a quote, a statistic, an insight with an icon) and the dark one, on three surfaces and in an article" -->
<!-- Generated by scripts/build-highlight-preview.js from tokens/css/tokens.css and components/highlight.css: don't edit, rebuild. -->
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Highlight</title>
<style>
${tokens}
/* The preview uses the uploaded Inter and Syne of the design system page when they're there. */
:root { --fds-font-typeface-inter: "Inter Variable Font opsz,wght", Inter, system-ui, sans-serif; }
${highlight}
/* Preview layout */
body { margin: 0; background: var(--fds-color-background); color: var(--fds-color-text); font-family: var(--fds-font-family-small); }
.panel { padding: var(--fds-space-8) var(--fds-space-6); background: var(--fds-color-background); }
.panel.subtle { background: var(--fds-color-surface-subtle); }
.panel.fds-surface-dark { background: var(--fds-color-surface-dark); }
.panel h2 { margin: 0 0 var(--fds-space-4); font: var(--fds-font-weight-overline) var(--fds-font-size-overline)/var(--fds-font-line-height-overline) var(--fds-font-family-overline); letter-spacing: var(--fds-font-letter-spacing-overline); text-transform: uppercase; }
.panel .note { margin: var(--fds-space-6) 0 var(--fds-space-3); font-size: var(--fds-font-size-small); font-weight: var(--fds-font-weight-small); color: var(--fds-color-text-muted); }
.panel > .fds-highlight, .article { max-width: calc(var(--fds-space-30) * 6); }
/* An article's own rules, as a case study page has them: more specific than a class and an element. */
body .article h3 { margin-top: var(--fds-space-10); margin-bottom: var(--fds-space-4); }
body .article p { margin: 0 0 var(--fds-space-5); font-size: var(--fds-font-size-body); line-height: var(--fds-font-line-height-body); }
.article > .fds-highlight { margin: var(--fds-space-8) 0; }
</style>
</head>
<body>
${SURFACES.map(panel).join('\n')}
${article}
</body>
</html>
`;

mkdirSync('docs', { recursive: true });
writeFileSync(OUT, html);
console.log(`✔︎ ${OUT}: light (quote, statistic, insight with an icon) and dark, on 3 surfaces and in an article.`);
