// Builds docs/tag-preview.html: every Tag variant on the page background, on a subtle surface, inside a
// dark surface and over a photo. From tokens/css/tokens.css and components/tag.css. It's the Tag's
// preview on the design system page and a page to open locally. Generated: don't edit, rebuild.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const OUT = 'docs/tag-preview.html';
const tokens = readFileSync('tokens/css/tokens.css', 'utf8').replace(/^\/\*\*[\s\S]*?\*\/\s*/, '');
const tag = readFileSync('components/tag.css', 'utf8');

// A neutral 16:10 picture, so the preview needs no image file.
const PICTURE = 'data:image/svg+xml,' + encodeURIComponent(
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 1000"><rect width="1600" height="1000" fill="#B3C8E6"/>'
  + '<rect x="420" y="180" width="760" height="520" rx="24" fill="#FFFFFF"/><rect x="480" y="250" width="320" height="28" rx="14" fill="#E4EAF4"/>'
  + '<rect x="480" y="420" width="640" height="220" rx="16" fill="#F5F1EB"/><circle cx="1240" cy="760" r="120" fill="#E8B84B"/></svg>');

const t = (label, cls = '', dot = false) =>
  `<span class="fds-tag${cls ? ' ' + cls : ''}">${dot ? '<span class="fds-tag__dot" aria-hidden="true"></span>' : ''}${label}</span>`;
const li = (label, cls = '') => `<li class="fds-tag${cls ? ' ' + cls : ''}">${label}</li>`;
const row = (note, inner) => `
    <p class="note">${note}</p>
    ${inner}`;

// The status dot is for light surfaces only (color-success has no dark-surface value).
const lightRows = (dark) =>
  row('Default: a topic, a role and a year', `<ul class="tags" aria-label="Example tags">${li('Design process')}${li('Lead designer')}${li('2026')}</ul>`)
  + (dark ? '' : row('Default with a status dot', `<div class="tags">${t('Open to new work', '', true)}</div>`))
  + row('Filled (selected or current) and Muted (pushed back)', `<div class="tags">${t('Selected topic', 'fds-tag--filled')}${t('Other topic', 'fds-tag--muted')}${t('Another topic')}</div>`);

const darkRows = () =>
  row('Default, Accent and Filled: accent is the one thing to notice in a row', `<div class="tags">${t('Core skill', 'fds-tag--accent')}${t('Also involved')}${t('Selected skill', 'fds-tag--filled')}</div>`)
  + row('Muted: the same tags pushed back, by colour and not by opacity (a Filled tag is never muted)', `<div class="tags">${t('Core skill', 'fds-tag--accent fds-tag--muted')}${t('Also involved', 'fds-tag--muted')}</div>`);

const photo = `
    <p class="note">On a photo: a tag that is itself a dark surface, with a solid fill</p>
    <div class="photo" style="background-image: url('${PICTURE}')">${t('Case study', 'fds-surface-dark')}</div>`;

const SURFACES = [['Page background', '', lightRows()], ['Subtle surface', ' subtle', lightRows()], ['Dark surface', ' fds-surface-dark', lightRows(true) + darkRows()]];
const panel = ([name, cls, rows]) => `
  <section class="panel${cls}">
    <h2>${name}</h2>${rows}${name === 'Page background' ? photo : ''}
  </section>`;

const html = `<!-- @dsCard group="Components" height=900 width=1200 subtitle="Static label pills in four variants, in one size, on three surfaces and over a photo" -->
<!-- Generated by scripts/build-tag-preview.js from tokens/css/tokens.css and components/tag.css: don't edit, rebuild. -->
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Tag</title>
<style>
${tokens}
/* The preview uses the uploaded Inter of the design system page when it's there. */
:root { --fds-font-typeface-inter: "Inter Variable Font opsz,wght", Inter, system-ui, sans-serif; }
${tag}
/* Preview layout */
body { margin: 0; background: var(--fds-color-background); color: var(--fds-color-text); font-family: var(--fds-font-family-small); }
.panel { padding: var(--fds-space-8) var(--fds-space-6); background: var(--fds-color-background); }
.panel.subtle { background: var(--fds-color-surface-subtle); }
.panel.fds-surface-dark { background: var(--fds-color-surface-dark); }
.panel h2 { margin: 0 0 var(--fds-space-4); font: var(--fds-font-weight-overline) var(--fds-font-size-overline)/var(--fds-font-line-height-overline) var(--fds-font-family-overline); letter-spacing: var(--fds-font-letter-spacing-overline); text-transform: uppercase; }
.panel .note { margin: var(--fds-space-6) 0 var(--fds-space-3); font-size: var(--fds-font-size-small); font-weight: var(--fds-font-weight-small); color: var(--fds-color-text-muted); }
.tags { display: flex; flex-wrap: wrap; gap: var(--fds-space-2); margin: 0; padding: 0; list-style: none; }
.photo { display: flex; align-items: flex-end; width: calc(var(--fds-space-30) * 3); max-width: 100%; aspect-ratio: 16 / 10; padding: var(--fds-space-4); box-sizing: border-box; border-radius: var(--fds-radius-lg); background-size: cover; }
</style>
</head>
<body>
${SURFACES.map(panel).join('\n')}
</body>
</html>
`;

mkdirSync('docs', { recursive: true });
writeFileSync(OUT, html);
console.log(`✔︎ ${OUT}: 4 variants on 3 surfaces and over a photo.`);
