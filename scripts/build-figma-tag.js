// Builds tokens/figma/tag-component.js: a Figma plugin script, run through the Figma MCP use_figma
// tool, that writes the Tag component set and the Tag page (decisions 58, 69, 70). Tag is one size:
// the overline text style, space-1 above and below, space-3 at the sides, a border-width/default
// border, radius/pill.
//
// Style (Default, Accent, Filled) × Muted (No, Yes), without a muted Filled tag: five variants. A
// Show dot property turns the status dot on, and Label is the text. The Default tag has no fill and
// no colour mode of its own, so it follows the frame it is placed in: navy text on a light surface, light
// text on a dark one. The Accent tag is gold text and a gold border on a solid color/surface-dark fill,
// in the Dark surface mode. The Filled tag is a color/accent fill with color/text-on-accent. Muted uses
// color/text-muted and the plain border. A tag over a photo is a Default tag set to the Dark surface
// mode with a color/surface-dark fill, as .fds-surface-dark does in code.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { DOC_RUNTIME } from './figma-doc-layout.js';

const OUT_DIR = 'tokens/figma/';
const OUT_FILE = `${OUT_DIR}tag-component.js`;

const SHARED = {
  padY: 'space/1', padX: 'space/3', gap: 'space/2', radius: 'radius/pill', strokeWeight: 'border-width/default',
  textStyle: 'overline', dotSize: 'space/2', photoInset: 'space/4', photoWidth: 360,
  text: 'color/text', muted: 'color/text-muted', border: 'color/border', accent: 'color/accent',
  onAccent: 'color/text-on-accent', dark: 'color/surface-dark', success: 'color/success',
  darkMode: 'Dark surface',
  props: { label: 'Label', showDot: 'Show dot' },
  defaults: { label: 'Design process' },
};

// The colour roles here must be exactly the ones tag.css uses.
const css = readFileSync('components/tag.css', 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const inCss = new Set([...css.matchAll(/var\(--fds-color-([\w-]+)\)/g)].map((m) => `color/${m[1]}`));
const inPlan = new Set([SHARED.text, SHARED.muted, SHARED.border, SHARED.accent, SHARED.onAccent, SHARED.dark, SHARED.success]);
const drift = [
  ...[...inCss].filter((r) => !inPlan.has(r)).map((r) => `${r} is in tag.css but not in the Figma tag`),
  ...[...inPlan].filter((r) => !inCss.has(r)).map((r) => `${r} is in the Figma tag but not in tag.css`),
];

// The Tag page's text comes from docs/tag.md: the first sentence for the page, the second for the
// "Component set" section, and the sentence under "Variants" for "Variants".
const doc = readFileSync('docs/tag.md', 'utf8');
const [purpose, setSubtitle] = doc.split('\n').find((l) => l && !l.startsWith('#')).split(/(?<=\.) /);
const variantsSubtitle = doc.split('\n## Variants\n')[1]?.trim().split('\n')[0];
if (!variantsSubtitle || variantsSubtitle.startsWith('|')) drift.push('docs/tag.md has no sentence under "## Variants"');
if (drift.length) {
  console.error('Figma tag build failed:\n' + drift.map((e) => `  ✗ ${e}`).join('\n'));
  process.exit(1);
}

const variants = [
  { style: 'Default', muted: 'No' }, { style: 'Default', muted: 'Yes' },
  { style: 'Accent', muted: 'No' }, { style: 'Accent', muted: 'Yes' },
  { style: 'Filled', muted: 'No' },
];

const plan = {
  variants, shared: SHARED, page: 'Tag', imagePage: 'Image', purpose, setSubtitle, variantsSubtitle,
  surfaces: [['Page background', 'Light surface', null], ['Subtle surface', 'Light surface', 'color/surface-subtle'], ['Dark surface', 'Dark surface', null]],
};

const script = `// Generated by scripts/build-figma-tag.js: don't edit, rebuild.
// Figma plugin script for the Figma MCP use_figma tool. It updates the Tag component set on the Tag
// page in place (variants by name; missing ones created, none deleted) and rebuilds the page around it
// (decision 58), top to bottom: the purpose, the set, and "Variants" on the page background, a subtle
// surface, a dark surface and a photo. Needs the Image component (image-component.js, for the photo),
// the color, spacing, radius and border-width variables and the text styles. Safe to run again:
// variant IDs stay the same; their layers are rebuilt.
const PLAN = ${JSON.stringify(plan, null, 2)};

${DOC_RUNTIME}

const S = PLAN.shared;
const bind = (node, field, name) => node.setBoundVariable(field, docVar(name));
const RADII = ['topLeftRadius', 'topRightRadius', 'bottomLeftRadius', 'bottomRightRadius'];
const value = (name) => { const v = docVar(name); return v.valuesByMode[Object.keys(v.valuesByMode)[0]]; };

const imagePage = figma.root.children.find((p) => p.name === PLAN.imagePage);
if (!imagePage) throw new Error('No Image page: run image-component.js first.');
await imagePage.loadAsync();
const imageComponent = imagePage.findOne((n) => n.type === 'COMPONENT' && n.name === 'Image');
if (!imageComponent) throw new Error('No Image component: run image-component.js first.');

const componentPage = await docPage(PLAN.page);
let set = componentPage.findOne((n) => n.type === 'COMPONENT_SET' && n.name === 'Tag');

// Rebuilds the inside of one variant. The variant node (and its ID) stays.
async function fill(comp, v) {
  for (const child of [...comp.children]) child.remove();
  comp.layoutMode = 'HORIZONTAL';
  comp.primaryAxisSizingMode = 'AUTO';
  comp.counterAxisSizingMode = 'AUTO';
  comp.counterAxisAlignItems = 'CENTER';
  comp.clipsContent = false;
  bind(comp, 'paddingTop', S.padY); bind(comp, 'paddingBottom', S.padY);
  bind(comp, 'paddingLeft', S.padX); bind(comp, 'paddingRight', S.padX);
  bind(comp, 'itemSpacing', S.gap);
  RADII.forEach((f) => bind(comp, f, S.radius));
  bind(comp, 'strokeWeight', S.strokeWeight);
  comp.strokeAlign = 'INSIDE';
  const [tc, tid] = docModeOf('typography', 'Desktop');
  comp.setExplicitVariableModeForCollection(tc, tid);
  // Only the Accent tag has a colour mode of its own: it is for a dark surface. The others follow the frame they are in.
  if (v.style === 'Accent') {
    const [cc, cid] = docModeOf('color', S.darkMode);
    comp.setExplicitVariableModeForCollection(cc, cid);
  }
  const muted = v.muted === 'Yes';
  let textColor = muted ? S.muted : S.text;
  comp.fills = [];
  comp.strokes = [docPaint(S.border)];
  if (v.style === 'Accent') {
    comp.fills = [docPaint(S.dark)];
    comp.strokes = [docPaint(muted ? S.border : S.accent)];
    textColor = muted ? S.muted : S.accent;
  } else if (v.style === 'Filled') {
    comp.fills = [docPaint(S.accent)];
    comp.strokes = [docPaint(S.accent)];
    textColor = S.onAccent;
  }

  const dot = figma.createFrame();
  dot.name = 'dot';
  comp.appendChild(dot);
  dot.layoutSizingHorizontal = 'FIXED'; dot.layoutSizingVertical = 'FIXED';
  bind(dot, 'width', S.dotSize); bind(dot, 'height', S.dotSize);
  RADII.forEach((f) => bind(dot, f, S.radius));
  dot.fills = [docPaint(S.success)];
  dot.visible = false;

  const label = await docText(S.defaults.label, S.textStyle, textColor);
  label.name = 'label';
  label.textAutoResize = 'WIDTH_AND_HEIGHT';
  comp.appendChild(label);
  return comp;
}

const variantName = (v) => 'Style=' + v.style + ', Muted=' + v.muted;
const ids = { updated: [], created: [] };
const fresh = [];
for (const v of PLAN.variants) {
  let comp = set ? set.findChild((n) => n.name === variantName(v)) : null;
  if (comp) ids.updated.push(comp.id);
  else { comp = figma.createComponent(); comp.name = variantName(v); fresh.push(comp); }
  await fill(comp, v);
}
if (!set) {
  set = figma.combineAsVariants(fresh, componentPage);
  set.name = 'Tag';
} else {
  for (const comp of fresh) set.appendChild(comp);
}
ids.created = fresh.map((c) => c.id);
set.description = 'A static label in a pill, in one size: never clickable, so it has no hover, focus or pressed state. Default (follows the surface), Accent (gold on a solid dark fill, dark surfaces only), Filled (gold fill) and Muted (pushed back by colour, not opacity). Show dot adds a status dot, for light surfaces. Decisions 69, 70. Bound to the color, spacing, radius and border-width variables and the overline text style. Same as components/tag.css.';

// Text and boolean properties: found by name, created once, then every variant's layers point to them.
const propKey = (name, type, val) => Object.keys(set.componentPropertyDefinitions).find((k) => k.split('#')[0] === name)
  ?? set.addComponentProperty(name, type, val);
const keys = {
  label: propKey(S.props.label, 'TEXT', S.defaults.label),
  showDot: propKey(S.props.showDot, 'BOOLEAN', false),
};
for (const comp of set.children) {
  comp.findOne((n) => n.name === 'label').componentPropertyReferences = { characters: keys.label };
  comp.findOne((n) => n.name === 'dot').componentPropertyReferences = { visible: keys.showDot };
}

// Lay the variants out in one row.
set.layoutMode = 'NONE';
const GAP = 32, PAD = 24;
let x = PAD, tallest = 0;
for (const v of PLAN.variants) {
  const comp = set.findChild((n) => n.name === variantName(v));
  comp.x = x; comp.y = PAD;
  x += comp.width + GAP;
  tallest = Math.max(tallest, comp.height);
}
set.resize(x - GAP + PAD, tallest + PAD * 2);
set.fills = [];

// The set's frame, kept between runs, on a light surface. The Accent tags carry their own dark fill.
let holder = set.parent.type === 'FRAME' && set.parent.name === 'Component set' ? set.parent : null;
if (!holder) {
  holder = figma.createFrame();
  holder.name = 'Component set';
  componentPage.appendChild(holder);
  holder.appendChild(set);
}
docSurface(holder, 'Light surface');
for (const child of [...holder.children]) if (child !== set) child.remove();
set.x = 0; set.y = 0;
holder.resize(set.width, set.height);

// A bound paint also stores a fallback colour, and Figma draws main components with it. Set it to
// the value the variable resolves to where the paint is.
async function resolvePaints(node) {
  if (node.type === 'INSTANCE') return;
  for (const field of ['fills', 'strokes']) {
    const paints = node[field];
    if (!Array.isArray(paints) || !paints.some((p) => p.boundVariables?.color)) continue;
    const next = [];
    for (const p of paints) {
      if (!p.boundVariables?.color) { next.push(p); continue; }
      const variable = await figma.variables.getVariableByIdAsync(p.boundVariables.color.id);
      const { r, g, b } = variable.resolveForConsumer(node).value;
      next.push(figma.variables.setBoundVariableForPaint(Object.assign({}, p, { color: { r, g, b } }), 'color', variable));
    }
    node[field] = next;
  }
  if ('children' in node) for (const child of node.children) await resolvePaints(child);
}
await resolvePaints(holder);

// ── The page around the set: rebuilt on every run ──
for (const child of [...componentPage.children]) if (child !== holder) child.remove();
const root = docRoot(componentPage, 1440);
await docSection(root, 'Tag', PLAN.purpose);
const setSection = await docSection(root, 'Component set', PLAN.setSubtitle, 'subheading');
const slot = figma.createFrame();
slot.name = 'Component set placeholder'; slot.fills = [];
slot.resize(holder.width, holder.height);
setSection.appendChild(slot);

const variantsSection = await docSection(root, 'Variants', PLAN.variantsSubtitle, 'subheading');
const instance = (style, muted, label, dot) => {
  const inst = set.findChild((n) => n.name === variantName({ style, muted })).createInstance();
  inst.setProperties({ [keys.label]: label, [keys.showDot]: !!dot });
  return inst;
};
const tagRow = async (frame, title, tags) => {
  frame.appendChild(await docText(title, 'small', 'color/text-muted'));
  const line = docFrame('tags', 'HORIZONTAL', { itemSpacing: 8, counterAxisAlignItems: 'CENTER' });
  frame.appendChild(line);
  for (const [style, muted, label, dot] of tags) line.appendChild(instance(style, muted, label, dot));
};

for (const [name, mode, fillRole] of PLAN.surfaces) {
  const dark = mode === 'Dark surface';
  const frame = docFrame(name, 'VERTICAL', { itemSpacing: 24, paddingTop: 40, paddingBottom: 40, paddingLeft: 40, paddingRight: 40 });
  variantsSection.appendChild(frame);
  docSurface(frame, mode);
  if (fillRole) frame.fills = [docPaint(fillRole)];
  frame.appendChild(await docText(name, 'overline', 'color/text-muted'));
  await tagRow(frame, 'Default: a topic, a role and a year', [['Default', 'No', 'Design process'], ['Default', 'No', 'Lead designer'], ['Default', 'No', '2026']]);
  if (!dark) await tagRow(frame, 'Default with a status dot', [['Default', 'No', 'Open to new work', true]]);
  await tagRow(frame, 'Filled (selected or current) and Muted (pushed back)', [['Filled', 'No', dark ? 'Selected topic' : 'Selected topic'], ['Default', 'Yes', 'Other topic'], ['Default', 'No', 'Another topic']]);
  if (dark) {
    await tagRow(frame, 'Default, Accent and Filled: accent is the one thing to notice in a row', [['Accent', 'No', 'Core skill'], ['Default', 'No', 'Also involved'], ['Filled', 'No', 'Selected skill']]);
    await tagRow(frame, 'Muted: the same tags pushed back, by colour and not by opacity (a Filled tag is never muted)', [['Accent', 'Yes', 'Core skill'], ['Default', 'Yes', 'Also involved']]);
  }
}

// On a photo: a Default tag that is itself a dark surface (the Dark surface mode and a solid dark fill).
const photoFrame = docFrame('On a photo', 'VERTICAL', { itemSpacing: 24, paddingTop: 40, paddingBottom: 40, paddingLeft: 40, paddingRight: 40 });
variantsSection.appendChild(photoFrame);
docSurface(photoFrame, 'Light surface');
photoFrame.appendChild(await docText('On a photo', 'overline', 'color/text-muted'));
photoFrame.appendChild(await docText('A tag over a picture is a tag that is itself a dark surface, so its text stays readable on any photo.', 'small', 'color/text-muted'));
const photo = docFrame('photo', 'VERTICAL', {});
photoFrame.appendChild(photo);
const picture = imageComponent.createInstance();
picture.name = 'image';
photo.appendChild(picture);
picture.resize(S.photoWidth, S.photoWidth * imageComponent.height / imageComponent.width);
bind(photo, 'topLeftRadius', 'radius/lg'); bind(photo, 'topRightRadius', 'radius/lg');
bind(photo, 'bottomLeftRadius', 'radius/lg'); bind(photo, 'bottomRightRadius', 'radius/lg');
photo.clipsContent = true;
const overPhoto = instance('Default', 'No', 'Case study');
photo.appendChild(overPhoto);
overPhoto.layoutPositioning = 'ABSOLUTE';
const [cc, cid] = docModeOf('color', S.darkMode);
overPhoto.setExplicitVariableModeForCollection(cc, cid);
overPhoto.fills = [docPaint(S.dark)];
overPhoto.x = value(S.photoInset);
overPhoto.y = picture.height - overPhoto.height - value(S.photoInset);

root.resize(root.paddingLeft + Math.max(...root.children.map((c) => c.width)) + root.paddingRight, root.height);
docUnclip(root);
docFitShadows(root);
componentPage.appendChild(holder);
holder.x = slot.absoluteBoundingBox.x;
holder.y = slot.absoluteBoundingBox.y;
docUnclip(holder);

const frames = Object.fromEntries(variantsSection.children.filter((c) => c.type === 'FRAME').map((c) => [c.name, c.id]));
return { componentSetId: set.id, variants: set.children.length, updated: ids.updated.length, created: ids.created.length,
  variantIds: set.children.map((c) => c.id).sort(), properties: Object.keys(set.componentPropertyDefinitions), page: componentPage.id,
  frames, holderId: holder.id, rootId: root.id, order: figma.root.children.map((p) => p.name) };
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, script);
console.log(`✔︎ ${OUT_FILE}: ${variants.length} Tag variants, roles match components/tag.css.`);
