// Builds tokens/figma/foundations-pages.js: a Figma plugin script, run through the Figma MCP use_figma
// tool, that rebuilds the Spacing, Corner radius and Shadows pages (decision 58). It's their only
// writer. Each page shows every token with a visual sample, its name, value and what it's for, taken
// from the token descriptions; samples are bound to the variables and effect styles Tokens Studio
// imports, so they change with them.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { DOC_RUNTIME } from './figma-doc-layout.js';

const OUT_DIR = 'tokens/figma/';
const OUT_FILE = `${OUT_DIR}foundations-pages.js`;

const read = (file) => JSON.parse(readFileSync(`tokens/${file}`, 'utf8'));
const dimension = read('dimension.tokens.json');
const effect = read('effect.tokens.json');
const names = (group) => Object.keys(group).filter((k) => !k.startsWith('$'));
const sentences = (text) => text.split(/(?<=\.) /);
const tidy = (text) => (text ?? '').replaceAll("'", '’');

const errors = [];

// Spacing: fixed steps are variables; the fluid steps are code only, shown at their largest value.
const spacing = names(dimension.space).map((key) => {
  const t = dimension.space[key];
  const fluid = String(t.$value).match(/^clamp\(\s*([\d.]+)px\s*,[^,]+,\s*([\d.]+)px\s*\)$/);
  if (fluid) return { name: `space-${key}`, value: `${fluid[1]} → ${fluid[2]}px, fluid (code only)`, width: Number(fluid[2]), description: tidy(t.$description) };
  return { name: `space/${key}`, variable: `space/${key}`, value: t.$value, description: tidy(t.$description) };
});

// Corner radius: a percentage stays in code; the README says what to use in Figma instead.
const readme = readFileSync('README.md', 'utf8');
const roundNote = readme.split('\n').find((l) => l.startsWith('`radius-round` exists in code only.'))?.replace(/`/g, '');
if (!roundNote) errors.push('README.md has no "`radius-round` exists in code only." line');
const radius = names(dimension.radius).map((key) => {
  const t = dimension.radius[key];
  const codeOnly = String(t.$value).endsWith('%');
  return { name: codeOnly ? `radius-${key}` : `radius/${key}`, variable: codeOnly ? null : `radius/${key}`, wide: key === 'pill',
    value: codeOnly ? `${t.$value} (code only)` : t.$value, description: tidy(t.$description) + (codeOnly ? ' ' + roundNote : '') };
});
if (!dimension.radius.$description) errors.push('The radius group has no $description for the page subtitle');

// Shadows: shown with the effect styles of the same name.
const shadows = names(effect.shadow).map((key) => {
  const v = effect.shadow[key].$value;
  return { name: `shadow/${key}`, value: `${v.offsetX} ${v.offsetY} ${v.blur} ${v.spread} ${v.color}`, description: tidy(effect.shadow[key].$description) };
});

if (errors.length) {
  console.error(`Figma foundations build failed (${errors.length}):\n` + errors.map((e) => `  ✗ ${e}`).join('\n'));
  process.exit(1);
}

const plan = {
  spacing: { subtitle: sentences(dimension.space.$description)[1], items: spacing },
  radius: { subtitle: dimension.radius.$description, items: radius },
  shadows: { subtitle: sentences(effect.shadow.$description)[1], items: shadows },
};

const script = `// Generated by scripts/build-figma-foundations.js from the token sources: don't edit, rebuild.
// Figma plugin script for the Figma MCP use_figma tool. It rebuilds the Spacing, Corner radius and
// Shadows pages. Needs the spacing, radius and color variables, the shadow effect styles and the
// text styles. Safe to run again.
const PLAN = ${JSON.stringify(plan, null, 2)};
${DOC_RUNTIME}
const effectStyles = await figma.getLocalEffectStylesAsync();
const bindRadius = (node, name) => ['topLeftRadius', 'topRightRadius', 'bottomLeftRadius', 'bottomRightRadius'].forEach((f) => node.setBoundVariable(f, docVar(name)));

// One row per token: the sample, then its name, value and what it's for.
async function tokenRow(parent, sample, item) {
  const row = docFrame(item.name, 'HORIZONTAL', { itemSpacing: 40, counterAxisAlignItems: 'CENTER' });
  parent.appendChild(row);
  const slot = docFrame('sample', 'HORIZONTAL', { counterAxisAlignItems: 'CENTER' });
  row.appendChild(slot);
  slot.primaryAxisSizingMode = 'FIXED'; slot.counterAxisSizingMode = 'FIXED'; slot.resize(280, Math.max(48, sample.height + 32));
  slot.appendChild(sample);
  const info = docFrame('info', 'VERTICAL', { itemSpacing: 4 });
  row.appendChild(info);
  info.appendChild(await docText(item.name, 'body', 'color/text', 760));
  info.appendChild(await docText(item.value, 'small', 'color/text-muted', 760));
  info.appendChild(await docText(item.description, 'small', 'color/text-muted', 760));
}

const pages = {};

// ── Spacing ──
{
  const page = await docPage('Spacing');
  for (const child of [...page.children]) child.remove();
  const root = docRoot(page, 1440);
  const section = await docSection(root, 'Spacing', PLAN.spacing.subtitle);
  const list = docFrame('steps', 'VERTICAL', { itemSpacing: 8 });
  section.appendChild(list);
  for (const item of PLAN.spacing.items) {
    const bar = figma.createFrame();
    bar.name = 'bar'; bar.resize(item.width || 4, 24);
    bar.fills = [docPaint('color/border-highlight')];
    if (item.variable) bar.setBoundVariable('width', docVar(item.variable));
    await tokenRow(list, bar, item);
  }
  docUnclip(root);
  docFitShadows(root);
  pages.spacing = page.id;
}

// ── Corner radius ──
{
  const page = await docPage('Corner radius');
  for (const child of [...page.children]) child.remove();
  const root = docRoot(page, 1440);
  const section = await docSection(root, 'Corner radius', PLAN.radius.subtitle);
  const list = docFrame('steps', 'VERTICAL', { itemSpacing: 24 });
  section.appendChild(list);
  for (const item of PLAN.radius.items) {
    const box = figma.createFrame();
    box.name = 'box'; box.resize(item.wide ? 200 : 96, item.wide ? 64 : 96);
    box.fills = [docPaint('color/surface-highlight')];
    box.strokes = [docPaint('color/border-highlight')];
    box.setBoundVariable('strokeWeight', docVar('border-width/control'));
    bindRadius(box, item.variable || 'radius/pill');
    await tokenRow(list, box, item);
  }
  docUnclip(root);
  docFitShadows(root);
  pages.radius = page.id;
}

// ── Shadows ──
{
  const page = await docPage('Shadows');
  for (const child of [...page.children]) child.remove();
  const root = docRoot(page, 1440);
  const section = await docSection(root, 'Shadows', PLAN.shadows.subtitle);
  const list = docFrame('levels', 'VERTICAL', { itemSpacing: 48 });
  section.appendChild(list);
  for (const item of PLAN.shadows.items) {
    const card = figma.createFrame();
    card.name = 'card'; card.resize(200, 120);
    card.fills = [docPaint('color/surface')];
    bindRadius(card, 'radius/lg');
    const style = effectStyles.find((s) => s.name === item.name);
    if (!style) throw new Error('Effect style not found: ' + item.name);
    await card.setEffectStyleIdAsync(style.id);
    await tokenRow(list, card, item);
  }
  docUnclip(root);
  docFitShadows(root);
  pages.shadows = page.id;
}

docOrder();
return { pages, order: figma.root.children.map((p) => p.name) };
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, script);
console.log(`✔︎ ${OUT_FILE}: Spacing (${spacing.length}), Corner radius (${radius.length}), Shadows (${shadows.length}).`);
