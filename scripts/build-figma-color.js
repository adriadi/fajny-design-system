// Builds tokens/figma/color-collection.js: a Figma plugin script, run through the Figma MCP
// use_figma tool, that writes the whole "color" variable collection (decision 43). It is the only
// writer of that collection: tokens-studio.json leaves the color set out, because Tokens Studio
// finds a collection's mode by name and would add a new mode next to "Light surface".
//
// Everything comes from the token sources and scripts/surfaces.js, so after a token change a rebuild
// and one run update Figma (decision 44). The collection gets two modes:
// - Light surface: each role's value from color-semantic.tokens.json.
// - Dark surface: the value the role takes inside .fds-surface-dark. Roles in DARK_SURFACE take
//   their -on-dark token, resolved to a primitive. Every other role keeps its light value; an alias
//   of another role is resolved to its primitive, so it doesn't follow that role's dark value.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { DARK_SURFACE, LIGHT_ONLY } from './surfaces.js';

const OUT_DIR = 'tokens/figma/';
const OUT_FILE = `${OUT_DIR}color-collection.js`;
const LIGHT_MODE = 'Light surface';
const DARK_MODE = 'Dark surface';
const LIGHT_ONLY_NOTE = 'Light surfaces only.';

const read = (file) => JSON.parse(readFileSync(`tokens/${file}`, 'utf8'));
const semantic = read('color-semantic.tokens.json').color;

// Figma variable scopes: which pickers in Figma offer each role.
const scopesFor = (name) => {
  if (name === 'text' || name.startsWith('text-')) return ['TEXT_FILL'];
  if (name === 'error' || name === 'success') return ['TEXT_FILL', 'STROKE_COLOR'];
  if (name.startsWith('border') || name === 'focus') return ['STROKE_COLOR'];
  if (['background', 'action', 'action-hover', 'accent'].includes(name) || name.startsWith('surface')) {
    return ['FRAME_FILL', 'SHAPE_FILL'];
  }
};

// '{navy.900}' -> 'navy.900'
const refOf = (value) => String(value).match(/^\{(.+)\}$/)?.[1];
// Follows color.* aliases down to a primitive path, e.g. 'color.text-muted' -> 'stone.600'.
const toPrimitive = (path) => {
  while (path.startsWith('color.')) {
    const token = semantic[path.slice('color.'.length)];
    if (!token) throw new Error(`Unknown token {${path}}`);
    path = refOf(token.$value);
    if (!path) throw new Error(`A colour role must be an alias, found ${token.$value}`);
  }
  return path;
};
const figmaName = (path) => path.replaceAll('.', '/');

const roles = [];
const errors = [];
for (const [name, token] of Object.entries(semantic)) {
  if (name.startsWith('$') || name.endsWith('-on-dark')) continue;
  const light = refOf(token.$value);
  if (!light) { errors.push(`color.${name} is not an alias`); continue; }
  const darkToken = DARK_SURFACE[`color-${name}`];
  const dark = darkToken
    ? toPrimitive(`color.${darkToken.slice('color-'.length)}`)
    : toPrimitive(light);
  const scopes = scopesFor(name);
  if (!scopes) errors.push(`color.${name} has no Figma scope`);
  let description = (token.$description ?? '').replaceAll("'", '’');
  // Light-only roles say so in Figma, unless the description already does.
  if (LIGHT_ONLY.includes(`color-${name}`) && !description.includes(LIGHT_ONLY_NOTE.slice(0, -1))) {
    description = `${description} ${LIGHT_ONLY_NOTE}`.trim();
  }
  roles.push({ name: `color/${name}`, light: figmaName(light), dark: figmaName(dark), scopes, description });
}

if (errors.length) {
  console.error(`Figma colour build failed (${errors.length}):\n` + errors.map((e) => `  ✗ ${e}`).join('\n'));
  process.exit(1);
}

const plan = { collection: 'color', primitives: 'primitives', lightMode: LIGHT_MODE, darkMode: DARK_MODE, roles };

const script = `// Generated by scripts/build-figma-color.js from the token sources: don't edit, rebuild.
// Figma plugin script for the Figma MCP use_figma tool. It writes the "color" collection:
// modes, aliases to the primitives collection, scopes and descriptions. Safe to run again.
const PLAN = ${JSON.stringify(plan, null, 2)};

const collections = await figma.variables.getLocalVariableCollectionsAsync();
const collection = collections.find((c) => c.name === PLAN.collection)
  ?? figma.variables.createVariableCollection(PLAN.collection);
const primitives = collections.find((c) => c.name === PLAN.primitives);
if (!primitives) throw new Error('No "' + PLAN.primitives + '" collection: import tokens-studio.json with Tokens Studio first.');

// Modes: the first mode becomes "${LIGHT_MODE}", then "${DARK_MODE}" is found or added.
let light = collection.modes.find((m) => m.name === PLAN.lightMode);
if (!light) {
  collection.renameMode(collection.modes[0].modeId, PLAN.lightMode);
  light = collection.modes[0];
}
const lightId = light.modeId;
const darkId = collection.modes.find((m) => m.name === PLAN.darkMode)?.modeId
  ?? collection.addMode(PLAN.darkMode);

const variables = await figma.variables.getLocalVariablesAsync('COLOR');
const byName = (collectionId, name) => variables.find((v) => v.variableCollectionId === collectionId && v.name === name);

// Roles first, so an alias of another role finds it.
const created = [];
const roleVars = {};
for (const role of PLAN.roles) {
  let v = byName(collection.id, role.name);
  if (!v) { v = figma.variables.createVariable(role.name, collection, 'COLOR'); created.push(role.name); }
  roleVars[role.name] = v;
}
const target = (name) => {
  const v = name.startsWith('color/') ? roleVars[name] : byName(primitives.id, name);
  if (!v) throw new Error('Alias target not found: ' + name);
  return figma.variables.createVariableAlias(v);
};

for (const role of PLAN.roles) {
  const v = roleVars[role.name];
  v.setValueForMode(lightId, target(role.light));
  v.setValueForMode(darkId, target(role.dark));
  v.scopes = role.scopes;
  v.description = role.description;
  v.hiddenFromPublishing = false;
}

const known = new Set(PLAN.roles.map((r) => r.name));
const extra = variables.filter((v) => v.variableCollectionId === collection.id && !known.has(v.name)).map((v) => v.name);

return {
  collectionId: collection.id,
  modes: collection.modes.map((m) => m.name),
  roles: PLAN.roles.length,
  createdVariables: created,
  notInTokens: extra,
};
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, script);
console.log(`✔︎ ${OUT_FILE}: ${roles.length} colour roles, modes "${LIGHT_MODE}" and "${DARK_MODE}".`);
