// Builds tokens/figma/image-component.js: a Figma plugin script, run through the Figma MCP use_figma
// tool, that writes the Image component and the Image page (decisions 58, 63). The component is a
// 16:10 frame filled with color-surface-subtle, a placeholder a designer swaps for a picture: a picture
// icon and a caption with its ratio and size (decision 66). It has no radius of its own: the component
// it's nested in rounds it, as the Card does. The page shows the component and the export sizes for a
// card and for a case study, both taken from docs/image.md.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { DOC_RUNTIME } from './figma-doc-layout.js';
import { ICONS } from './card-icons.js';

const OUT_DIR = 'tokens/figma/';
const OUT_FILE = `${OUT_DIR}image-component.js`;

const css = readFileSync('components/image.css', 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const ratio = css.match(/aspect-ratio:\s*(\d+)\s*\/\s*(\d+)/);
const fill = css.match(/background-color:\s*var\(--fds-(color-[\w-]+)\)/)?.[1];

const doc = readFileSync('docs/image.md', 'utf8');
const section = (title) => doc.split(`\n## ${title}\n`)[1]?.split('\n## ')[0] ?? '';
const [purpose, componentSubtitle] = doc.split('\n').find((l) => l && !l.startsWith('#')).split(/(?<=\.) /);
const exportSubtitle = section('Export sizes').trim().split('\n')[0];
const exportRows = section('Export sizes').split('\n')
  .filter((l) => l.startsWith('| ') && !l.startsWith('| Category') && !l.startsWith('| ---'))
  .map((l) => l.split('|').slice(1, -1).map((c) => c.trim().replaceAll('`', '')));

// The "Case study images" section: its first sentence is the subtitle, its bullets the body.
const caseStudy = section('Case study images').trim().split('\n');
const caseStudySubtitle = caseStudy[0].split(/(?<=\.) /)[0];
const caseStudyBullets = caseStudy.filter((l) => l.startsWith('- ')).map((l) => l.replace(/^- /, '').replaceAll('`', '').replaceAll('**', ''));

const errors = [];
if (!caseStudyBullets.length) errors.push('docs/image.md has no bullets under "## Case study images"');
if (!ratio) errors.push('components/image.css sets no aspect-ratio');
if (!fill) errors.push('components/image.css sets no background-color role');
if (!exportSubtitle || exportSubtitle.startsWith('|')) errors.push('docs/image.md has no sentence under "## Export sizes"');
if (!exportRows.length) errors.push('docs/image.md has no export sizes table');
if (errors.length) {
  console.error('Figma image build failed:\n' + errors.map((e) => `  ✗ ${e}`).join('\n'));
  process.exit(1);
}

const [, , cardRatio, cardPixels] = exportRows[0];
const figmaSvg = (svg) => svg.replace(/ data-icon="\w+"| aria-hidden="true"| focusable="false"/g, '').replace('currentColor', 'black');

const plan = {
  width: 320, // the default width in Figma; the height follows the ratio
  placeholder: { icon: figmaSvg(ICONS.image), caption: `${cardRatio} · ${cardPixels}`, iconSize: 'space/6', gap: 'space/2', color: 'color/text-muted', style: 'small' },
  ratio: [Number(ratio[1]), Number(ratio[2])],
  fill: fill.replace('color-', 'color/'),
  page: 'Image', purpose, componentSubtitle, exportSubtitle,
  exportHeader: ['Category', 'Size', 'Ratio', 'Pixels', 'Use'],
  exportRows, caseStudy: { title: 'Case study images', subtitle: caseStudySubtitle, bullets: caseStudyBullets },
};

const script = `// Generated by scripts/build-figma-image.js: don't edit, rebuild.
// Figma plugin script for the Figma MCP use_figma tool. It updates the Image component on the Image
// page in place (found by name, its ID stays) and rebuilds the page around it (decision 58): the
// purpose, the component, and the export sizes. Needs the color variables and the text styles.
// Safe to run again.
const PLAN = ${JSON.stringify(plan, null, 2)};

${DOC_RUNTIME}

const page = await docPage(PLAN.page);
let image = page.findOne((n) => n.type === 'COMPONENT' && n.name === 'Image');
const created = !image;
if (!image) image = figma.createComponent();
image.name = 'Image';
image.description = 'A picture inside a component, at 16:10 (decision 63). Swap the placeholder fill for the picture. No radius of its own: the component it sits in rounds it. Export at the sizes on the Image page.';
for (const child of [...image.children]) child.remove();
// The placeholder: a picture icon over a caption with the ratio and the export size, centred.
image.layoutMode = 'VERTICAL';
image.primaryAxisSizingMode = 'FIXED'; image.counterAxisSizingMode = 'FIXED';
image.primaryAxisAlignItems = 'CENTER'; image.counterAxisAlignItems = 'CENTER';
image.resize(PLAN.width, PLAN.width * PLAN.ratio[1] / PLAN.ratio[0]);
image.setBoundVariable('itemSpacing', docVar(PLAN.placeholder.gap));
{
  const icon = figma.createNodeFromSvg(PLAN.placeholder.icon);
  icon.name = 'icon';
  icon.fills = [];
  const size = docVar(PLAN.placeholder.iconSize);
  icon.rescale(size.valuesByMode[Object.keys(size.valuesByMode)[0]] / icon.width);
  for (const v of icon.findAll((n) => n.type === 'VECTOR')) v.strokes = [docPaint(PLAN.placeholder.color)];
  image.appendChild(icon);
  const caption = await docText(PLAN.placeholder.caption, PLAN.placeholder.style, PLAN.placeholder.color);
  caption.name = 'caption';
  caption.textAutoResize = 'WIDTH_AND_HEIGHT';
  image.appendChild(caption);
}
image.fills = [docPaint(PLAN.fill)];
image.strokes = [];
image.clipsContent = false;
if (typeof image.lockAspectRatio === 'function') image.lockAspectRatio();

// The component sits in a frame with the light surface mode, so its bound fill shows; the frame is
// kept between runs. The paint's fallback colour is set to the resolved value, which Figma draws
// main components with.
let holder = image.parent.type === 'FRAME' && image.parent.name === 'Component' ? image.parent : null;
if (!holder) {
  holder = figma.createFrame();
  holder.name = 'Component';
  page.appendChild(holder);
  holder.appendChild(image);
}
docSurface(holder, 'Light surface');
image.x = 0; image.y = 0;
holder.resize(image.width, image.height);
{
  const p = image.fills[0];
  const variable = await figma.variables.getVariableByIdAsync(p.boundVariables.color.id);
  const { r, g, b } = variable.resolveForConsumer(image).value;
  image.fills = [figma.variables.setBoundVariableForPaint(Object.assign({}, p, { color: { r, g, b } }), 'color', variable)];
}

for (const child of [...page.children]) if (child !== holder) child.remove();
const root = docRoot(page, 1440);
await docSection(root, 'Image', PLAN.purpose);
const componentSection = await docSection(root, 'Component', PLAN.componentSubtitle, 'subheading');
const slot = figma.createFrame();
slot.name = 'Component placeholder'; slot.fills = [];
slot.resize(holder.width, holder.height);
componentSection.appendChild(slot);

const sizes = await docSection(root, 'Export sizes', PLAN.exportSubtitle, 'subheading');
const table = docFrame('sizes', 'VERTICAL', { itemSpacing: 16 });
sizes.appendChild(table);
const COLUMNS = [140, 120, 100, 200, 640];
const row = async (cells, header) => {
  const line = docFrame(cells[0] + ' ' + cells[1], 'HORIZONTAL', { itemSpacing: 24 });
  table.appendChild(line);
  for (let i = 0; i < cells.length; i++) {
    line.appendChild(await docText(cells[i], header ? 'overline' : i === 0 ? 'body' : 'small', header || i > 0 ? 'color/text-muted' : 'color/text', COLUMNS[i]));
  }
};
await row(PLAN.exportHeader, true);
for (const cells of PLAN.exportRows) await row(cells, false);

// Case study pictures keep their own ratio: shown as text, not as a frame.
const study = await docSection(root, PLAN.caseStudy.title, PLAN.caseStudy.subtitle, 'subheading');
for (const bullet of PLAN.caseStudy.bullets) study.appendChild(await docText('• ' + bullet, 'body', 'color/text', 880));

docUnclip(root);
docFitShadows(root);
page.appendChild(holder);
holder.x = slot.absoluteBoundingBox.x;
holder.y = slot.absoluteBoundingBox.y;

return { imageId: image.id, created, size: [image.width, image.height], page: page.id, order: figma.root.children.map((p) => p.name) };
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, script);
console.log(`✔︎ ${OUT_FILE}: the Image component at ${plan.ratio.join(':')}, ${exportRows.length} export sizes.`);
