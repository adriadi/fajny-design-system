// Builds docs/input-preview.html: a form to try, then every Input type in every state, on a light
// surface (fields are light-only, decision 60). From tokens/css/tokens.css, components/input.css and
// components/button.css. It's the Input's preview on the design system page and a page to open
// locally. Generated: don't edit, rebuild.
//
// The form to try is the copy-paste HTML of docs/input.md, run with the two scripts from the same
// page, so the docs can't show anything the preview doesn't run. Hover and focus can't be shown at
// rest, so the preview copies those rules of input.css onto data-preview attributes.
// The build fails if docs/input.md shows icons other than scripts/input-icons.js.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { ICONS } from './input-icons.js';
import { TYPES, DISABLED_HELP } from './input-examples.js';

const OUT = 'docs/input-preview.html';
const tokens = readFileSync('tokens/css/tokens.css', 'utf8').replace(/^\/\*\*[\s\S]*?\*\/\s*/, '');
const input = readFileSync('components/input.css', 'utf8');
const button = readFileSync('components/button.css', 'utf8');
const doc = readFileSync('docs/input.md', 'utf8');

const errors = [];
const blocks = (lang) => [...doc.matchAll(new RegExp('```' + lang + '\\n([\\s\\S]*?)```', 'g'))].map((m) => m[1]);
const [form] = blocks('html');
const scripts = blocks('js');
if (!form) errors.push('docs/input.md has no ```html block');
if (scripts.length !== 2) errors.push(`docs/input.md has ${scripts.length} \`\`\`js blocks; expected 2 (error check, show/hide)`);
const docIcons = doc.replaceAll(' hidden viewBox', ' viewBox');
for (const [name, svg] of Object.entries(ICONS)) {
  if (!docIcons.includes(svg)) errors.push(`docs/input.md doesn't show the ${name} icon exactly as scripts/input-icons.js draws it`);
}
if (errors.length) {
  console.error(`Input preview build failed (${errors.length}):\n` + errors.map((e) => `  ✗ ${e}`).join('\n'));
  process.exit(1);
}

const forced = input
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .match(/[^{}]+\{[^{}]*\}/g)
  .filter((rule) => /:hover|:focus-visible/.test(rule))
  .map((rule) => rule.trim()
    .replace(/:hover/g, '[data-preview="hover"]')
    .replace(/:focus-visible/g, '[data-preview="focus"]'))
  .join('\n');

const STATES = ['Default', 'Hover', 'Focus', 'Filled', 'Error', 'Disabled'];

let n = 0;
const cell = (type, state) => {
  const id = `p${++n}`;
  const error = state === 'Error';
  const filled = state === 'Filled' || state === 'Disabled';
  const attrs = [
    state === 'Hover' && 'data-preview="hover"',
    state === 'Focus' && 'data-preview="focus"',
    state === 'Disabled' && 'disabled',
    error && 'aria-invalid="true"',
    `aria-describedby="${id}-${error ? 'error' : 'help'}"`,
  ].filter(Boolean).join(' ');
  let field;
  if (type.name === 'Select') {
    const chosen = filled ? ' selected' : '';
    field = `<select class="fds-input" id="${id}" ${attrs}><option value="">${type.placeholder}</option><option${chosen}>${type.value}</option></select>`;
  } else if (type.name === 'Textarea') {
    const value = error ? type.wrong : filled ? type.value : '';
    field = `<textarea class="fds-input" id="${id}" placeholder="${type.placeholder}" ${attrs}>${value}</textarea>`;
  } else {
    const value = error ? type.wrong : filled ? type.value : '';
    const kind = type.name === 'Password' ? 'password' : 'email';
    field = `<input class="fds-input" id="${id}" type="${kind}" placeholder="${type.placeholder}" value="${value}" ${attrs}>`;
  }
  const action = type.name === 'Password'
    ? `<button class="fds-field__action" type="button" aria-controls="${id}" aria-label="Show password" data-toggle-password${state === 'Disabled' ? ' disabled' : ''}>${ICONS.show}${ICONS.hide.replace(' viewBox', ' hidden viewBox')}</button>`
    : '';
  const help = state === 'Disabled' ? DISABLED_HELP : type.help;
  return `<td><div class="fds-field">
          <label class="fds-field__label" for="${id}">${type.label}</label>
          ${field}${action}
          <p class="fds-field__help" id="${id}-help"${error ? ' hidden' : ''}>${help}</p>${error ? `
          <p class="fds-field__error" id="${id}-error">${ICONS.warning}${type.error}</p>` : ''}
        </div></td>`;
};

const html = `<!-- @dsCard group="Components" height=900 width=1200 subtitle="Text, select, text area and password, every state, with a form to try" -->
<!-- Generated by scripts/build-input-preview.js from tokens/css/tokens.css, components/input.css and docs/input.md: don't edit, rebuild. -->
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Input</title>
<style>
${tokens}
/* The preview uses the uploaded Inter of the design system page when it's there. */
:root { --fds-font-typeface-inter: "Inter Variable Font opsz,wght", Inter, system-ui, sans-serif; }
${button}
${input}
/* Preview only: hover and focus shown at rest. */
${forced}
/* Preview layout */
body { margin: 0; background: var(--fds-color-background); color: var(--fds-color-text); font-family: var(--fds-font-family-small); }
.panel { box-sizing: border-box; width: max-content; min-width: 100%; padding: var(--fds-space-6); }
.panel h2 { margin: 0 0 var(--fds-space-4); font: var(--fds-font-weight-overline) var(--fds-font-size-overline)/var(--fds-font-line-height-overline) var(--fds-font-family-overline); letter-spacing: var(--fds-font-letter-spacing-overline); text-transform: uppercase; }
.try form { display: grid; gap: var(--fds-space-6); width: calc(var(--fds-space-30) * 4); }
.try form > .fds-button { justify-self: start; }
.try output { font-size: var(--fds-font-size-small); color: var(--fds-color-text-muted); }
table { border-collapse: separate; border-spacing: var(--fds-space-6) var(--fds-space-4); margin: 0 calc(-1 * var(--fds-space-6)); }
th { text-align: left; vertical-align: top; font-size: var(--fds-font-size-small); font-weight: var(--fds-font-weight-small); color: var(--fds-color-text-muted); }
td { vertical-align: top; width: calc(var(--fds-space-30) * 2); }
</style>
</head>
<body>
  <section class="panel try">
    <h2>Try it</h2>
${form.trim().split('\n').map((l) => '    ' + l).join('\n')}
    <output id="result" role="status"></output>
  </section>
  <section class="panel">
    <h2>Every type in every state</h2>
    <table>
      <thead><tr><th></th>${STATES.map((s) => `<th>${s}</th>`).join('')}</tr></thead>
      <tbody>
${TYPES.map((t) => `        <tr><th>${t.name}</th>${STATES.map((s) => cell(t, s)).join('')}</tr>`).join('\n')}
      </tbody>
    </table>
  </section>
<script>
${scripts.join('\n')}
// Preview only: a valid form isn't sent anywhere.
document.querySelector('.try form').addEventListener('submit', (event) => {
  const valid = !event.defaultPrevented;
  event.preventDefault();
  document.getElementById('result').textContent = valid ? 'Every field is valid. Nothing was sent: this is a preview.' : '';
});
</script>
</body>
</html>
`;

mkdirSync('docs', { recursive: true });
writeFileSync(OUT, html);
console.log(`✔︎ ${OUT}: ${TYPES.length} types × ${STATES.length} states, a form to try, icons match docs/input.md.`);
