// Builds tokens/figma/navigation-component.js: a Figma plugin script, run through the Figma MCP use_figma
// tool, that writes the Navigation component set and the Navigation page (decisions 58, 72). The call to
// action is an instance of the Button (Primary, Navigation size), so the page belongs to the Advanced group.
//
// Type (Full, Minimal) × Layout (Wide, Collapsed) × Menu (Closed, Open): four variants. Wide is 1200px,
// collapsed is 390px; the open menu is the drawer under the bar. The bar has a solid color/background fill,
// a border-width/default line under it in color/border and a space/16 height. The current link has a
// border-width/default underline in color/border-rule, and its text takes the same role (decision 73): navy
// on a light surface, gold in the Dark surface mode. A dark navigation is an instance set to the Dark surface
// mode with a color/surface-dark fill, as .fds-surface-dark does in code.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { DOC_RUNTIME } from './figma-doc-layout.js';

const OUT_DIR = 'tokens/figma/';
const OUT_FILE = `${OUT_DIR}navigation-component.js`;

const SHARED = {
  wide: 1200, collapsed: 390, height: 'space/16', gutterWide: 'space/12', gutterCollapsed: 'space/4',
  barGap: 'space/6', linkGap: 'space/10', drawerGap: 'space/6', drawerTop: 'space/4', drawerBottom: 'space/8',
  underlinePad: 'space/1', toggle: 'space/10', weight: 'border-width/default', shadow: 'shadow/md',
  textStyle: 'label',
  background: 'color/background', border: 'color/border', text: 'color/text', muted: 'color/text-muted',
  rule: 'color/border-rule', dark: 'color/surface-dark', darkMode: 'Dark surface',
  button: { page: 'Button', set: 'Button', variant: 'Variant=Primary, Size=Navigation, State=Default' },
  defaults: { brand: 'Brand name', links: ['Work', 'About', 'Journal'], cta: 'Contact', back: '← All work', current: 0 },
  props: { brand: 'Brand' },
  bars: 'M0 4h24M0 12h24M0 20h24', cross: 'M3.5 3.5L20.5 20.5M20.5 3.5L3.5 20.5',
};

// The colour roles here must be the ones navigation.css and button.css use (the focus ring isn't drawn).
const roles = (file) => new Set([...readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/var\(--fds-color-([\w-]+)\)/g)].map((m) => `color/${m[1]}`));
const inNav = roles('components/navigation.css');
const inButton = roles('components/button.css');
const inPlan = new Set([SHARED.background, SHARED.border, SHARED.text, SHARED.muted, SHARED.rule, SHARED.dark]);
const drift = [
  ...[...inNav].filter((r) => r !== 'color/focus' && !inPlan.has(r)).map((r) => `${r} is in navigation.css but not in the Figma navigation`),
  ...[...inPlan].filter((r) => !inNav.has(r) && !inButton.has(r)).map((r) => `${r} is in the Figma navigation but not in navigation.css or button.css`),
];

// The page's text comes from docs/navigation.md: the first sentence for the page, the second for the
// "Component set" section, and the sentence under "Variants" for "Variants".
const doc = readFileSync('docs/navigation.md', 'utf8');
const [purpose, setSubtitle] = doc.split('\n').find((l) => l && !l.startsWith('#')).split(/(?<=\.) /);
const variantsSubtitle = doc.split('\n## Variants\n')[1]?.trim().split('\n')[0];
if (!variantsSubtitle || variantsSubtitle.startsWith('|')) drift.push('docs/navigation.md has no sentence under "## Variants"');
if (drift.length) {
  console.error('Figma navigation build failed:\n' + drift.map((e) => `  ✗ ${e}`).join('\n'));
  process.exit(1);
}

const variants = [
  { type: 'Full', layout: 'Wide', menu: 'Closed' },
  { type: 'Full', layout: 'Collapsed', menu: 'Closed' },
  { type: 'Full', layout: 'Collapsed', menu: 'Open' },
  { type: 'Minimal', layout: 'Wide', menu: 'Closed' },
];

const plan = { variants, shared: SHARED, page: 'Navigation', purpose, setSubtitle, variantsSubtitle };

const script = `// Generated by scripts/build-figma-navigation.js: don't edit, rebuild.
// Figma plugin script for the Figma MCP use_figma tool. It updates the Navigation component set on the
// Navigation page in place (variants by name; missing ones created, none deleted) and rebuilds the page
// around it (decision 58), top to bottom: the purpose, the set, and "Variants" on the page background and
// a dark surface. Needs the Button component (button-component.js, for the call to action), the color,
// spacing and border-width variables, the shadow effect styles and the text styles. Safe to run again:
// variant IDs stay the same; their layers are rebuilt.
const PLAN = ${JSON.stringify(plan, null, 2)};

${DOC_RUNTIME}

const S = PLAN.shared;
const bind = (node, field, name) => node.setBoundVariable(field, docVar(name));
const effectStyles = await figma.getLocalEffectStylesAsync();

const buttonPage = figma.root.children.find((p) => p.name === S.button.page);
if (!buttonPage) throw new Error('No Button page: run button-component.js first.');
await buttonPage.loadAsync();
const buttonSet = buttonPage.findOne((n) => n.type === 'COMPONENT_SET' && n.name === S.button.set);
const ctaVariant = buttonSet && buttonSet.findChild((n) => n.name === S.button.variant);
if (!ctaVariant) throw new Error('No Button variant ' + S.button.variant + ': run button-component.js first.');

const componentPage = await docPage(PLAN.page);
let set = componentPage.findOne((n) => n.type === 'COMPONENT_SET' && n.name === 'Navigation');

const label = async (chars, color, name) => {
  const t = await docText(chars, S.textStyle, color);
  t.name = name;
  t.textAutoResize = 'WIDTH_AND_HEIGHT';
  return t;
};

// A link: its text, with the current-page underline (border-bottom, color/border-rule) under it.
async function link(chars, current, name) {
  const f = docFrame(name, 'VERTICAL', { itemSpacing: 0 });
  bind(f, 'paddingBottom', S.underlinePad);
  f.appendChild(await label(chars, current ? S.rule : S.muted, 'text'));
  if (current) {
    f.strokes = [docPaint(S.rule)];
    f.strokeAlign = 'INSIDE';
    f.strokeTopWeight = 0; f.strokeLeftWeight = 0; f.strokeRightWeight = 0;
    bind(f, 'strokeBottomWeight', S.weight);
  }
  return f;
}

function icon(svg, name) {
  const node = figma.createNodeFromSvg('<svg viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg"><path d="' + svg + '" stroke="black" stroke-width="1.5"/></svg>');
  node.name = name;
  node.fills = [];
  for (const vec of node.findAll((n) => n.type === 'VECTOR')) vec.strokes = [docPaint(S.text)];
  return node;
}

function cta(chars) {
  const inst = ctaVariant.createInstance();
  inst.name = 'call to action';
  const t = inst.findOne((n) => n.type === 'TEXT');
  if (t) t.characters = chars;
  return inst;
}

// Rebuilds the inside of one variant. The variant node (and its ID) stays.
async function fill(comp, v) {
  for (const child of [...comp.children]) child.remove();
  const wide = v.layout === 'Wide';
  comp.layoutMode = 'VERTICAL';
  comp.primaryAxisSizingMode = 'AUTO';
  comp.counterAxisSizingMode = 'FIXED';
  comp.resize(wide ? S.wide : S.collapsed, comp.height);
  comp.itemSpacing = 0;
  comp.clipsContent = false;
  comp.fills = [docPaint(S.background)];
  const [tc, tid] = docModeOf('typography', 'Desktop');
  comp.setExplicitVariableModeForCollection(tc, tid);

  const bar = docFrame('bar', 'HORIZONTAL', { counterAxisAlignItems: 'CENTER', primaryAxisAlignItems: 'SPACE_BETWEEN' });
  comp.appendChild(bar);
  bar.layoutSizingHorizontal = 'FILL';
  bar.layoutSizingVertical = 'FIXED';
  bind(bar, 'height', S.height);
  bind(bar, 'paddingLeft', wide ? S.gutterWide : S.gutterCollapsed);
  bind(bar, 'paddingRight', wide ? S.gutterWide : S.gutterCollapsed);
  bind(bar, 'itemSpacing', S.barGap);
  bar.strokes = [docPaint(S.border)];
  bar.strokeAlign = 'INSIDE';
  bar.strokeTopWeight = 0; bar.strokeLeftWeight = 0; bar.strokeRightWeight = 0;
  bind(bar, 'strokeBottomWeight', S.weight);

  bar.appendChild(await label(S.defaults.brand, S.text, 'brand'));

  if (v.type === 'Minimal') {
    bar.appendChild(await link(S.defaults.back, false, 'back link'));
  } else if (wide) {
    const menu = docFrame('menu', 'HORIZONTAL', { counterAxisAlignItems: 'CENTER' });
    bar.appendChild(menu);
    bind(menu, 'itemSpacing', S.linkGap);
    for (let i = 0; i < S.defaults.links.length; i++) menu.appendChild(await link(S.defaults.links[i], i === S.defaults.current, 'link ' + (i + 1)));
    menu.appendChild(cta(S.defaults.cta));
  } else {
    const toggle = docFrame('menu button', 'HORIZONTAL', { primaryAxisAlignItems: 'CENTER', counterAxisAlignItems: 'CENTER' });
    bar.appendChild(toggle);
    toggle.layoutSizingHorizontal = 'FIXED'; toggle.layoutSizingVertical = 'FIXED';
    bind(toggle, 'width', S.toggle); bind(toggle, 'height', S.toggle);
    toggle.appendChild(icon(v.menu === 'Open' ? S.cross : S.bars, v.menu === 'Open' ? 'close icon' : 'menu icon'));
  }

  if (v.menu === 'Open') {
    const drawer = docFrame('drawer', 'VERTICAL', { counterAxisAlignItems: 'MIN' });
    comp.appendChild(drawer);
    drawer.layoutSizingHorizontal = 'FILL';
    drawer.fills = [docPaint(S.background)];
    bind(drawer, 'paddingTop', S.drawerTop); bind(drawer, 'paddingBottom', S.drawerBottom);
    bind(drawer, 'paddingLeft', S.gutterCollapsed); bind(drawer, 'paddingRight', S.gutterCollapsed);
    bind(drawer, 'itemSpacing', S.drawerGap);
    drawer.strokes = [docPaint(S.border)];
    drawer.strokeAlign = 'INSIDE';
    drawer.strokeTopWeight = 0; drawer.strokeLeftWeight = 0; drawer.strokeRightWeight = 0;
    bind(drawer, 'strokeBottomWeight', S.weight);
    const shadow = effectStyles.find((s) => s.name === S.shadow);
    if (shadow) await drawer.setEffectStyleIdAsync(shadow.id);
    for (let i = 0; i < S.defaults.links.length; i++) drawer.appendChild(await link(S.defaults.links[i], i === S.defaults.current, 'link ' + (i + 1)));
    const button = cta(S.defaults.cta);
    drawer.appendChild(button);
    button.layoutSizingHorizontal = 'FILL';
  }
  return comp;
}

const variantName = (v) => 'Type=' + v.type + ', Layout=' + v.layout + ', Menu=' + v.menu;
const ids = { updated: [], created: [] };
const fresh = [];
for (const v of PLAN.variants) {
  let comp = set ? set.findChild((n) => n.name === variantName(v)) : null;
  if (comp) ids.updated.push(comp.id);
  else { comp = figma.createComponent(); comp.name = variantName(v); fresh.push(comp); }
  await fill(comp, v);
}
if (!set) {
  set = figma.combineAsVariants(fresh, componentPage);
  set.name = 'Navigation';
} else {
  for (const comp of fresh) set.appendChild(comp);
}
ids.created = fresh.map((c) => c.id);
set.description = 'The bar at the top of a page: full (brand, links, a call to action that is a Button) or minimal (a brand name and a back link). When the links do not fit they sit in a drawer behind a menu button: Layout=Collapsed, Menu=Closed or Open. The current page has a 1.5px color-border-rule underline (navy; gold on a dark surface) and aria-current="page" in code. Decisions 72, 73. Bound to the color, spacing and border-width variables, the shadow-md effect style and the label text style. Same as components/navigation.css.';

// A text property for the brand name, found by name, created once, then every variant's layer points to it.
const brandKey = Object.keys(set.componentPropertyDefinitions).find((k) => k.split('#')[0] === S.props.brand)
  ?? set.addComponentProperty(S.props.brand, 'TEXT', S.defaults.brand);
for (const comp of set.children) comp.findOne((n) => n.name === 'brand').componentPropertyReferences = { characters: brandKey };

// Lay the variants out: the wide one, the two collapsed ones side by side, the minimal one.
set.layoutMode = 'NONE';
const GAP = 48, PAD = 24;
const at = (v) => set.findChild((n) => n.name === variantName(v));
const [wideFull, closed, open, minimal] = PLAN.variants.map(at);
wideFull.x = PAD; wideFull.y = PAD;
closed.x = PAD; closed.y = wideFull.y + wideFull.height + GAP;
open.x = PAD + closed.width + GAP; open.y = closed.y;
minimal.x = PAD; minimal.y = Math.max(closed.y + closed.height, open.y + open.height) + GAP;
set.resize(PAD * 2 + S.wide, minimal.y + minimal.height + PAD);
set.fills = [];

let holder = set.parent.type === 'FRAME' && set.parent.name === 'Component set' ? set.parent : null;
if (!holder) {
  holder = figma.createFrame();
  holder.name = 'Component set';
  componentPage.appendChild(holder);
  holder.appendChild(set);
}
docSurface(holder, 'Light surface');
for (const child of [...holder.children]) if (child !== set) child.remove();
set.x = 0; set.y = 0;
holder.resize(set.width, set.height);

// A bound paint also stores a fallback colour, and Figma draws main components with it. Set it to
// the value the variable resolves to where the paint is. Nested instances keep their main's paints.
async function resolvePaints(node) {
  if (node.type === 'INSTANCE') return;
  for (const field of ['fills', 'strokes']) {
    const paints = node[field];
    if (!Array.isArray(paints) || !paints.some((p) => p.boundVariables?.color)) continue;
    const next = [];
    for (const p of paints) {
      if (!p.boundVariables?.color) { next.push(p); continue; }
      const variable = await figma.variables.getVariableByIdAsync(p.boundVariables.color.id);
      const { r, g, b } = variable.resolveForConsumer(node).value;
      next.push(figma.variables.setBoundVariableForPaint(Object.assign({}, p, { color: { r, g, b } }), 'color', variable));
    }
    node[field] = next;
  }
  if ('children' in node) for (const child of node.children) await resolvePaints(child);
}
await resolvePaints(holder);

// ── The page around the set: rebuilt on every run ──
for (const child of [...componentPage.children]) if (child !== holder) child.remove();
const root = docRoot(componentPage, 1440);
await docSection(root, 'Navigation', PLAN.purpose);
const setSection = await docSection(root, 'Component set', PLAN.setSubtitle, 'subheading');
const slot = figma.createFrame();
slot.name = 'Component set placeholder'; slot.fills = [];
slot.resize(holder.width, holder.height);
setSection.appendChild(slot);

const variantsSection = await docSection(root, 'Variants', PLAN.variantsSubtitle, 'subheading');
const instance = (v) => at(v).createInstance();
const note = (frame, chars) => docText(chars, 'small', 'color/text-muted').then((t) => frame.appendChild(t));

// On the page background: every variant at rest.
const light = docFrame('Page background', 'VERTICAL', { itemSpacing: 24, paddingTop: 40, paddingBottom: 40, paddingLeft: 40, paddingRight: 40 });
variantsSection.appendChild(light);
docSurface(light, 'Light surface');
light.appendChild(await docText('Page background', 'overline', 'color/text-muted'));
await note(light, 'Full: the current page has the underline; the call to action is a Button');
light.appendChild(instance(PLAN.variants[0]));
await note(light, 'Collapsed, closed and open: the links sit in a drawer behind the menu button');
const pair = docFrame('collapsed', 'HORIZONTAL', { itemSpacing: 48, counterAxisAlignItems: 'MIN' });
light.appendChild(pair);
pair.appendChild(instance(PLAN.variants[1]));
pair.appendChild(instance(PLAN.variants[2]));
await note(light, 'Minimal: a brand name and a back link, for a case study');
light.appendChild(instance(PLAN.variants[3]));

// On a dark surface: the instance takes the Dark surface mode and a color/surface-dark fill.
const dark = docFrame('Dark surface', 'VERTICAL', { itemSpacing: 24, paddingTop: 40, paddingBottom: 40, paddingLeft: 40, paddingRight: 40 });
variantsSection.appendChild(dark);
docSurface(dark, 'Dark surface');
dark.appendChild(await docText('Dark surface', 'overline', 'color/text-muted'));
await note(dark, 'Full and minimal on a dark surface: the roles switch, the call to action turns gold, the current link and its underline turn gold');
const [cc, cid] = docModeOf('color', S.darkMode);
for (const v of [PLAN.variants[0], PLAN.variants[3]]) {
  const inst = instance(v);
  dark.appendChild(inst);
  inst.setExplicitVariableModeForCollection(cc, cid);
  inst.fills = [docPaint(S.dark)];
}

root.resize(root.paddingLeft + Math.max(...root.children.map((c) => c.width)) + root.paddingRight, root.height);
docUnclip(root);
docFitShadows(root);
componentPage.appendChild(holder);
holder.x = slot.absoluteBoundingBox.x;
holder.y = slot.absoluteBoundingBox.y;
docUnclip(holder);

return { componentSetId: set.id, variants: set.children.length, updated: ids.updated.length, created: ids.created.length,
  variantIds: set.children.map((c) => c.id).sort(), properties: Object.keys(set.componentPropertyDefinitions), page: componentPage.id,
  frames: { light: light.id, dark: dark.id }, holderId: holder.id, rootId: root.id, order: figma.root.children.map((p) => p.name) };
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, script);
console.log(`✔︎ ${OUT_FILE}: ${variants.length} Navigation variants, roles match components/navigation.css.`);
