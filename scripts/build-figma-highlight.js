// Builds tokens/figma/highlight-component.js: a Figma plugin script, run through the Figma MCP use_figma
// tool, that writes the Highlight component set and the Highlight page (decisions 58, 76). Needs the quote
// text style: run typography-collection.js first.
//
// Variant (Light, Dark): two variants. Light: a color/surface-highlight fill, a rule on the left only in
// color/border-highlight at border-width/default, square corners (decision 75), an optional icon, the quote in
// the quote text style (upright in Figma: Syne has no italic here) and the source in small, muted. Dark: a
// color/surface-dark fill, radius/sm, a label (overline), a heading (subheading) and two paragraphs (body,
// muted). Each variant carries its own colour mode (Light surface, Dark surface), so it looks the same wherever
// it is placed, as in code. Show icon and Show source are switches; the texts are properties.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { DOC_RUNTIME } from './figma-doc-layout.js';

const OUT_DIR = 'tokens/figma/';
const OUT_FILE = `${OUT_DIR}highlight-component.js`;

const SHARED = {
  width: 640, padY: 'space/6', padX: 'space/8', darkPadY: 'space/10', darkPadX: 'space/12', iconGap: 'space/4',
  citeGap: 'space/3', darkGap: 'space/4', paragraphGap: 'space/3', icon: 'space/5', weight: 'border-width/default',
  radius: 'radius/sm',
  fill: 'color/surface-highlight', rule: 'color/border-highlight', dark: 'color/surface-dark',
  text: 'color/text', muted: 'color/text-muted', modes: { Light: 'Light surface', Dark: 'Dark surface' },
  styles: { quote: 'quote', cite: 'small', label: 'overline', title: 'subheading', text: 'body' },
  iconPath: 'M21 12a9 9 0 1 1-3-6.7M21 4v5h-5',
  props: { quote: 'Quote', cite: 'Source', showIcon: 'Show icon', showCite: 'Show source', label: 'Label', title: 'Title', text1: 'Paragraph 1', text2: 'Paragraph 2' },
  defaults: {
    quote: '“Nothing ships unless the person it is for can understand it on day one.”', cite: 'Name · Role, Organisation',
    label: 'The core gap', title: 'One sentence that states it.',
    text1: 'One or two short paragraphs that say what follows from it.', text2: 'A second paragraph sits 12px under the first.',
  },
};

// The colour roles here must be exactly the ones highlight.css uses.
const css = readFileSync('components/highlight.css', 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const inCss = new Set([...css.matchAll(/var\(--fds-color-([\w-]+)\)/g)].map((m) => `color/${m[1]}`));
const inPlan = new Set([SHARED.fill, SHARED.rule, SHARED.dark, SHARED.text, SHARED.muted]);
const drift = [
  ...[...inCss].filter((r) => !inPlan.has(r)).map((r) => `${r} is in highlight.css but not in the Figma highlight`),
  ...[...inPlan].filter((r) => !inCss.has(r)).map((r) => `${r} is in the Figma highlight but not in highlight.css`),
];

// The page's text comes from docs/highlight.md: the first sentence for the page, the second for the
// "Component set" section, and the sentence under "Variants" for "Variants".
const doc = readFileSync('docs/highlight.md', 'utf8');
const [purpose, setSubtitle] = doc.split('\n').find((l) => l && !l.startsWith('#')).split(/(?<=\.) /);
const variantsSubtitle = doc.split('\n## Variants\n')[1]?.trim().split('\n')[0];
if (!variantsSubtitle || variantsSubtitle.startsWith('|')) drift.push('docs/highlight.md has no sentence under "## Variants"');
if (drift.length) {
  console.error('Figma highlight build failed:\n' + drift.map((e) => `  ✗ ${e}`).join('\n'));
  process.exit(1);
}

const variants = [{ variant: 'Light' }, { variant: 'Dark' }];
const plan = { variants, shared: SHARED, page: 'Highlight', purpose, setSubtitle, variantsSubtitle };

const script = `// Generated by scripts/build-figma-highlight.js: don't edit, rebuild.
// Figma plugin script for the Figma MCP use_figma tool. It updates the Highlight component set on the
// Highlight page in place (variants by name; missing ones created, none deleted) and rebuilds the page
// around it (decision 58), top to bottom: the purpose, the set, and "Variants" on the page background, a
// subtle surface and a dark surface. Needs the color, spacing, radius and border-width variables and the text
// styles, including quote (typography-collection.js). Safe to run again: variant IDs stay the same; their
// layers are rebuilt.
const PLAN = ${JSON.stringify(plan, null, 2)};

${DOC_RUNTIME}

const S = PLAN.shared;
const bind = (node, field, name) => node.setBoundVariable(field, docVar(name));
const RADII = ['topLeftRadius', 'topRightRadius', 'bottomLeftRadius', 'bottomRightRadius'];

const componentPage = await docPage(PLAN.page);
let set = componentPage.findOne((n) => n.type === 'COMPONENT_SET' && n.name === 'Highlight');

const text = async (chars, style, color, name) => {
  const t = await docText(chars, style, color);
  t.name = name;
  t.textAutoResize = 'HEIGHT';
  return t;
};

// Rebuilds the inside of one variant. The variant node (and its ID) stays.
async function fill(comp, v) {
  for (const child of [...comp.children]) child.remove();
  const dark = v.variant === 'Dark';
  comp.clipsContent = false;
  const [cc, cid] = docModeOf('color', S.modes[v.variant]);
  comp.setExplicitVariableModeForCollection(cc, cid);
  const [tc, tid] = docModeOf('typography', 'Desktop');
  comp.setExplicitVariableModeForCollection(tc, tid);

  if (dark) {
    comp.layoutMode = 'VERTICAL';
    // Vertical: the width is the counter axis (fixed), the height the primary axis (hugs).
    comp.primaryAxisSizingMode = 'AUTO'; comp.counterAxisSizingMode = 'FIXED';
    comp.resize(S.width, comp.height);
    comp.counterAxisAlignItems = 'MIN';
    comp.fills = [docPaint(S.dark)];
    comp.strokes = [];
    for (const f of ['paddingTop', 'paddingBottom']) bind(comp, f, S.darkPadY);
    for (const f of ['paddingLeft', 'paddingRight']) bind(comp, f, S.darkPadX);
    bind(comp, 'itemSpacing', S.darkGap);
    RADII.forEach((f) => bind(comp, f, S.radius));
    const label = await text(S.defaults.label, S.styles.label, S.text, 'label');
    comp.appendChild(label); label.layoutSizingHorizontal = 'FILL';
    const title = await text(S.defaults.title, S.styles.title, S.text, 'title');
    comp.appendChild(title); title.layoutSizingHorizontal = 'FILL';
    const texts = docFrame('text', 'VERTICAL', {});
    comp.appendChild(texts); texts.layoutSizingHorizontal = 'FILL';
    bind(texts, 'itemSpacing', S.paragraphGap);
    for (const [name, chars] of [['paragraph 1', S.defaults.text1], ['paragraph 2', S.defaults.text2]]) {
      const t = await text(chars, S.styles.text, S.muted, name);
      texts.appendChild(t); t.layoutSizingHorizontal = 'FILL';
    }
  } else {
    comp.layoutMode = 'HORIZONTAL';
    // Horizontal: the width is the primary axis (fixed), the height the counter axis (hugs).
    comp.primaryAxisSizingMode = 'FIXED'; comp.counterAxisSizingMode = 'AUTO';
    comp.resize(S.width, comp.height);
    comp.counterAxisAlignItems = 'MIN';
    comp.fills = [docPaint(S.fill)];
    for (const f of ['paddingTop', 'paddingBottom']) bind(comp, f, S.padY);
    for (const f of ['paddingLeft', 'paddingRight']) bind(comp, f, S.padX);
    bind(comp, 'itemSpacing', S.iconGap);
    RADII.forEach((f) => { comp.setBoundVariable(f, null); comp[f] = 0; });
    // The rule: the left edge only, border-width/default, square corners (decision 75).
    comp.strokes = [docPaint(S.rule)];
    comp.strokeAlign = 'INSIDE';
    comp.strokeTopWeight = 0; comp.strokeRightWeight = 0; comp.strokeBottomWeight = 0;
    bind(comp, 'strokeLeftWeight', S.weight);

    const icon = docFrame('icon', 'HORIZONTAL', { primaryAxisAlignItems: 'CENTER', counterAxisAlignItems: 'CENTER' });
    comp.appendChild(icon);
    icon.layoutSizingHorizontal = 'FIXED'; icon.layoutSizingVertical = 'FIXED';
    bind(icon, 'width', S.icon); bind(icon, 'height', S.icon);
    const glyph = figma.createNodeFromSvg('<svg viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg"><path d="' + S.iconPath + '" stroke="black" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/></svg>');
    glyph.name = 'glyph';
    glyph.fills = [];
    glyph.resize(value20(), value20());
    for (const vec of glyph.findAll((n) => n.type === 'VECTOR')) vec.strokes = [docPaint(S.text)];
    icon.appendChild(glyph);
    icon.visible = false;

    const body = docFrame('body', 'VERTICAL', {});
    comp.appendChild(body); body.layoutSizingHorizontal = 'FILL';
    bind(body, 'itemSpacing', S.citeGap);
    const quote = await text(S.defaults.quote, S.styles.quote, S.text, 'quote');
    body.appendChild(quote); quote.layoutSizingHorizontal = 'FILL';
    const cite = await text(S.defaults.cite, S.styles.cite, S.muted, 'source');
    body.appendChild(cite); cite.layoutSizingHorizontal = 'FILL';
  }
  return comp;
}
function value20() { const v = docVar(S.icon); return v.valuesByMode[Object.keys(v.valuesByMode)[0]]; }

const variantName = (v) => 'Variant=' + v.variant;
const ids = { updated: [], created: [] };
const fresh = [];
for (const v of PLAN.variants) {
  let comp = set ? set.findChild((n) => n.name === variantName(v)) : null;
  if (comp) ids.updated.push(comp.id);
  else { comp = figma.createComponent(); comp.name = variantName(v); fresh.push(comp); }
  await fill(comp, v);
}
if (!set) {
  set = figma.combineAsVariants(fresh, componentPage);
  set.name = 'Highlight';
} else {
  for (const comp of fresh) set.appendChild(comp);
}
ids.created = fresh.map((c) => c.id);
set.description = 'A block that sets one thing apart: Light (a quote, an insight or a cited statistic on color/surface-highlight, with a 1.5px rule on the left only, square corners and an optional icon; the quote is in the quote text style, which is italic in code and upright here) or Dark (the tension or decision of a story on color/surface-dark: a label, a heading and one or two paragraphs). Each carries its own colour mode, so it looks the same on any surface. Decisions 22, 75, 76. Bound to the color, spacing, radius and border-width variables and the text styles. Same as components/highlight.css.';

// Text and boolean properties: found by name, created once, then the layers point to them.
const propKey = (name, type, val) => Object.keys(set.componentPropertyDefinitions).find((k) => k.split('#')[0] === name)
  ?? set.addComponentProperty(name, type, val);
const P = S.props;
const keys = {
  quote: propKey(P.quote, 'TEXT', S.defaults.quote), cite: propKey(P.cite, 'TEXT', S.defaults.cite),
  showIcon: propKey(P.showIcon, 'BOOLEAN', false), showCite: propKey(P.showCite, 'BOOLEAN', true),
  label: propKey(P.label, 'TEXT', S.defaults.label), title: propKey(P.title, 'TEXT', S.defaults.title),
  text1: propKey(P.text1, 'TEXT', S.defaults.text1), text2: propKey(P.text2, 'TEXT', S.defaults.text2),
};
const light = set.findChild((n) => n.name === 'Variant=Light');
const darkVariant = set.findChild((n) => n.name === 'Variant=Dark');
light.findOne((n) => n.name === 'quote').componentPropertyReferences = { characters: keys.quote };
light.findOne((n) => n.name === 'source').componentPropertyReferences = { characters: keys.cite, visible: keys.showCite };
light.findOne((n) => n.name === 'icon').componentPropertyReferences = { visible: keys.showIcon };
darkVariant.findOne((n) => n.name === 'label').componentPropertyReferences = { characters: keys.label };
darkVariant.findOne((n) => n.name === 'title').componentPropertyReferences = { characters: keys.title };
darkVariant.findOne((n) => n.name === 'paragraph 1').componentPropertyReferences = { characters: keys.text1 };
darkVariant.findOne((n) => n.name === 'paragraph 2').componentPropertyReferences = { characters: keys.text2 };

// Lay the variants out side by side.
set.layoutMode = 'NONE';
const GAP = 48, PAD = 24;
light.x = PAD; light.y = PAD;
darkVariant.x = PAD + light.width + GAP; darkVariant.y = PAD;
set.resize(PAD * 2 + light.width + GAP + darkVariant.width, PAD * 2 + Math.max(light.height, darkVariant.height));
set.fills = [];

let holder = set.parent.type === 'FRAME' && set.parent.name === 'Component set' ? set.parent : null;
if (!holder) {
  holder = figma.createFrame();
  holder.name = 'Component set';
  componentPage.appendChild(holder);
  holder.appendChild(set);
}
docSurface(holder, 'Light surface');
for (const child of [...holder.children]) if (child !== set) child.remove();
set.x = 0; set.y = 0;
holder.resize(set.width, set.height);

// A bound paint also stores a fallback colour, and Figma draws main components with it. Set it to
// the value the variable resolves to where the paint is.
async function resolvePaints(node) {
  if (node.type === 'INSTANCE') return;
  for (const field of ['fills', 'strokes']) {
    const paints = node[field];
    if (!Array.isArray(paints) || !paints.some((p) => p.boundVariables?.color)) continue;
    const next = [];
    for (const p of paints) {
      if (!p.boundVariables?.color) { next.push(p); continue; }
      const variable = await figma.variables.getVariableByIdAsync(p.boundVariables.color.id);
      const { r, g, b } = variable.resolveForConsumer(node).value;
      next.push(figma.variables.setBoundVariableForPaint(Object.assign({}, p, { color: { r, g, b } }), 'color', variable));
    }
    node[field] = next;
  }
  if ('children' in node) for (const child of node.children) await resolvePaints(child);
}
await resolvePaints(holder);

// ── The page around the set: rebuilt on every run ──
for (const child of [...componentPage.children]) if (child !== holder) child.remove();
const root = docRoot(componentPage, 1440);
await docSection(root, 'Highlight', PLAN.purpose);
const setSection = await docSection(root, 'Component set', PLAN.setSubtitle, 'subheading');
const slot = figma.createFrame();
slot.name = 'Component set placeholder'; slot.fills = [];
slot.resize(holder.width, holder.height);
setSection.appendChild(slot);

const variantsSection = await docSection(root, 'Variants', PLAN.variantsSubtitle, 'subheading');
const instance = (name, props) => {
  const inst = set.findChild((n) => n.name === 'Variant=' + name).createInstance();
  if (props) inst.setProperties(props);
  return inst;
};
const note = async (frame, chars) => frame.appendChild(await docText(chars, 'small', 'color/text-muted'));

for (const [name, mode, fillRole] of [['Page background', 'Light surface', null], ['Subtle surface', 'Light surface', 'color/surface-subtle'], ['Dark surface', 'Dark surface', null]]) {
  const onDark = mode === 'Dark surface';
  const frame = docFrame(name, 'VERTICAL', { itemSpacing: 24, paddingTop: 40, paddingBottom: 40, paddingLeft: 40, paddingRight: 40 });
  variantsSection.appendChild(frame);
  docSurface(frame, mode);
  if (fillRole) frame.fills = [docPaint(fillRole)];
  frame.appendChild(await docText(name, 'overline', 'color/text-muted'));
  await note(frame, 'Light: a quote with its source, no icon');
  frame.appendChild(instance('Light'));
  await note(frame, 'Light: a cited statistic');
  frame.appendChild(instance('Light', { [keys.quote]: 'Nine in ten of the people we asked said the same thing.', [keys.cite]: 'Example survey · 2024 · Example organisation' }));
  await note(frame, 'Light with the icon slot: an insight, no source');
  frame.appendChild(instance('Light', { [keys.showIcon]: true, [keys.showCite]: false, [keys.quote]: 'Changes showed up on both devices at once, with no refresh and no waiting.' }));
  if (onDark) await note(frame, 'The light variant stays light on a dark surface; the dark variant is the same navy, so it is shown on the light surfaces');
  else { await note(frame, 'Dark: a label, a heading and two paragraphs; the label sits 16px above the heading'); frame.appendChild(instance('Dark')); }
}

root.resize(root.paddingLeft + Math.max(...root.children.map((c) => c.width)) + root.paddingRight, root.height);
docUnclip(root);
docFitShadows(root);
componentPage.appendChild(holder);
holder.x = slot.absoluteBoundingBox.x;
holder.y = slot.absoluteBoundingBox.y;
docUnclip(holder);

return { componentSetId: set.id, variants: set.children.length, updated: ids.updated.length, created: ids.created.length,
  variantIds: set.children.map((c) => c.id).sort(), properties: Object.keys(set.componentPropertyDefinitions), page: componentPage.id,
  frames: Object.fromEntries(variantsSection.children.filter((c) => c.type === 'FRAME' && c.name !== 'title').map((c) => [c.name, c.id])), holderId: holder.id, rootId: root.id,
  order: figma.root.children.map((p) => p.name) };
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, script);
console.log(`✔︎ ${OUT_FILE}: ${variants.length} Highlight variants, roles match components/highlight.css.`);
