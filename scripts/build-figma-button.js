// Builds tokens/figma/button-component.js: a Figma plugin script, run through the Figma MCP use_figma
// tool, that writes the Button component set and the "Button check" page (decisions 44, 45, 53, 56).
// Every fill, stroke, size, radius, opacity and text style is bound to a variable or the label text
// style, so a frame's "Dark surface" mode switches the button as .fds-surface-dark does in code.
//
// The variants and the roles each state uses are listed below, the same as components/button.css.
// The build fails if the two name different colour roles, so the Figma button can't drift from code.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const OUT_DIR = 'tokens/figma/';
const OUT_FILE = `${OUT_DIR}button-component.js`;

// Variant rows. fill/hover: frame fill; text/textHover: label colour; stroke: border colour;
// square: no rounded corners, so the focus ring is square as in CSS.
const VARIANTS = [
  { variant: 'Primary', size: 'Main', label: 'View my work', minHeight: 'space/12', paddingX: 'space/8',
    fill: 'color/action', fillHover: 'color/action-hover', text: 'color/text-on-action' },
  { variant: 'Secondary', size: 'Main', label: 'Download CV', minHeight: 'space/12', paddingX: 'space/8',
    fill: 'color/secondary', fillHover: 'color/secondary-hover', text: 'color/text-on-secondary', stroke: 'color/border-highlight' },
  { variant: 'Link', size: 'Main', label: 'Case studies', minHeight: 'space/6',
    text: 'color/text-muted', textHover: 'color/text', noDisable: true, square: true },
  { variant: 'Primary', size: 'Navigation', label: "Let's talk", minHeight: 'space/8', paddingX: 'space/6',
    fill: 'color/action', fillHover: 'color/action-hover', text: 'color/text-on-action' },
];
const STATES = ['Default', 'Hover', 'Focus', 'Active', 'Disabled', 'Loading'];
const SHARED = {
  gap: 'space/2', radius: 'radius/pill', strokeWeight: 'border-width/control', opacity: 'opacity/disabled',
  focusColor: 'color/focus', focusWidth: 'focus/ring-width', focusOffset: 'focus/ring-offset',
  textStyle: 'label', loadingLabel: 'Sending…',
};

// The colour roles here must be exactly the ones button.css uses.
const css = readFileSync('components/button.css', 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const inCss = new Set([...css.matchAll(/var\(--fds-color-([\w-]+)\)/g)].map((m) => `color/${m[1]}`));
const inPlan = new Set([...VARIANTS.flatMap((v) => [v.fill, v.fillHover, v.text, v.textHover, v.stroke]), SHARED.focusColor].filter(Boolean));
const missing = [...inCss].filter((r) => !inPlan.has(r)).map((r) => `${r} is in button.css but not in the Figma button`);
const extra = [...inPlan].filter((r) => !inCss.has(r)).map((r) => `${r} is in the Figma button but not in button.css`);
if (missing.length || extra.length) {
  console.error('Figma button build failed:\n' + [...missing, ...extra].map((e) => `  ✗ ${e}`).join('\n'));
  process.exit(1);
}

const plan = { variants: VARIANTS, states: STATES, shared: SHARED, componentPage: 'Button', checkPage: 'Button check' };

const script = `// Generated by scripts/build-figma-button.js: don't edit, rebuild.
// Figma plugin script for the Figma MCP use_figma tool. It updates the Button component set on the
// "Button" page in place (variants by name; missing ones created, none deleted) and rebuilds the
// "Button check" page. Needs the color, typography, spacing, radius, focus, border-width and opacity
// collections and the label text style. Safe to run again: variant IDs stay the same.
const PLAN = ${JSON.stringify(plan, null, 2)};

const vars = await figma.variables.getLocalVariablesAsync();
const v = (name) => {
  const found = vars.find((x) => x.name === name);
  if (!found) throw new Error('Variable not found: ' + name);
  return found;
};
const paint = (name) => figma.variables.setBoundVariableForPaint({ type: 'SOLID', color: { r: 0, g: 0, b: 0 } }, 'color', v(name));
const labelStyle = (await figma.getLocalTextStylesAsync()).find((s) => s.name === PLAN.shared.textStyle);
if (!labelStyle) throw new Error('No "' + PLAN.shared.textStyle + '" text style: run typography-collection.js first.');
await figma.loadFontAsync(labelStyle.fontName);
await figma.loadFontAsync({ family: 'Inter', style: 'Regular' });

const page = async (name) => {
  let p = figma.root.children.find((x) => x.name === name);
  if (!p) { p = figma.createPage(); p.name = name; }
  return p;
};

// ── The component set: updated in place ──
// Existing variants are found by name and updated, missing ones are created, none are deleted, so
// their IDs (and every instance in a design) stay the same from run to run.
const componentPage = await page(PLAN.componentPage);
await figma.setCurrentPageAsync(componentPage);
let set = componentPage.findChild((n) => n.type === 'COMPONENT_SET' && n.name === 'Button');

const RADII = ['topLeftRadius', 'topRightRadius', 'bottomLeftRadius', 'bottomRightRadius'];
const PADDING = ['paddingLeft', 'paddingRight', 'paddingTop', 'paddingBottom'];
const bindRadius = (node, on) => RADII.forEach((f) => { node.setBoundVariable(f, on ? v(PLAN.shared.radius) : null); if (!on) node[f] = 0; });
const unbind = (node, fields) => fields.forEach((f) => { node.setBoundVariable(f, null); node[f] = 0; });

// Sets every property of one variant, whatever it was before.
async function fill(comp, row, state) {
  const hover = state === 'Hover' || state === 'Active';
  comp.layoutMode = 'HORIZONTAL';
  comp.primaryAxisSizingMode = 'AUTO'; comp.counterAxisSizingMode = 'AUTO';
  comp.fills = [];
  bindRadius(comp, !row.square);
  if (state === 'Focus') {
    for (const f of PADDING) comp.setBoundVariable(f, v(PLAN.shared.focusOffset));
    comp.strokes = [paint(PLAN.shared.focusColor)];
    comp.strokeAlign = 'OUTSIDE';
    comp.setBoundVariable('strokeWeight', v(PLAN.shared.focusWidth));
  } else {
    unbind(comp, PADDING);
    comp.strokes = [];
    comp.setBoundVariable('strokeWeight', null);
  }
  if (state === 'Disabled') comp.setBoundVariable('opacity', v(PLAN.shared.opacity));
  else { comp.setBoundVariable('opacity', null); comp.opacity = 1; }

  let btn = comp.findChild((n) => n.name === 'button');
  if (!btn) { btn = figma.createFrame(); btn.name = 'button'; comp.appendChild(btn); }
  btn.layoutMode = 'HORIZONTAL';
  btn.primaryAxisSizingMode = 'AUTO'; btn.counterAxisSizingMode = 'AUTO';
  btn.primaryAxisAlignItems = 'CENTER'; btn.counterAxisAlignItems = 'CENTER';
  btn.setBoundVariable('itemSpacing', v(PLAN.shared.gap));
  btn.setBoundVariable('minHeight', v(row.minHeight));
  if (row.paddingX) { btn.setBoundVariable('paddingLeft', v(row.paddingX)); btn.setBoundVariable('paddingRight', v(row.paddingX)); }
  else unbind(btn, ['paddingLeft', 'paddingRight']);
  btn.fills = row.fill ? [paint(hover && row.fillHover ? row.fillHover : row.fill)] : [];
  bindRadius(btn, !!row.fill);
  if (row.stroke) {
    btn.strokes = [paint(row.stroke)];
    btn.strokeAlign = 'INSIDE';
    btn.setBoundVariable('strokeWeight', v(PLAN.shared.strokeWeight));
  } else { btn.strokes = []; btn.setBoundVariable('strokeWeight', null); }

  let text = btn.findChild((n) => n.type === 'TEXT');
  if (!text) { text = figma.createText(); btn.appendChild(text); }
  await text.setTextStyleIdAsync(labelStyle.id);
  text.characters = state === 'Loading' ? PLAN.shared.loadingLabel : row.label;
  text.fills = [paint(hover && row.textHover ? row.textHover : row.text)];
}

const ids = { updated: [], created: [] };
const fresh = [];
for (const row of PLAN.variants) {
  for (const state of PLAN.states) {
    if (row.noDisable && (state === 'Disabled' || state === 'Loading')) continue;
    const name = 'Variant=' + row.variant + ', Size=' + row.size + ', State=' + state;
    let comp = set ? set.findChild((n) => n.name === name) : null;
    if (comp) ids.updated.push(comp.id);
    else { comp = figma.createComponent(); comp.name = name; fresh.push(comp); }
    await fill(comp, row, state);
  }
}
if (!set) {
  set = figma.combineAsVariants(fresh, componentPage);
  set.name = 'Button';
} else {
  for (const comp of fresh) set.appendChild(comp);
}
ids.created = fresh.map((c) => c.id);
set.description = 'Primary, secondary and link, with a navigation size. Bound to the color, spacing, radius, focus, border-width and opacity variables and the label text style; a frame in "Dark surface" mode switches it. Same as components/button.css.';
// Lay the variants out in a grid: one row per variant row, one column per state.
set.layoutMode = 'NONE';
const COL = 260, ROWH = 90;
for (const comp of set.children) {
  const props = Object.fromEntries(comp.name.split(', ').map((p) => p.split('=')));
  const r = PLAN.variants.findIndex((x) => x.variant === props.Variant && x.size === props.Size);
  const c = PLAN.states.indexOf(props.State);
  if (r < 0 || c < 0) continue; // a variant the plan doesn't know stays where it is
  comp.x = 24 + c * COL; comp.y = 24 + r * ROWH;
}
set.resize(24 * 2 + PLAN.states.length * COL, 24 * 2 + PLAN.variants.length * ROWH);

// ── The "Button check" page: every variant and state, light and dark ──
const checkPage = await page(PLAN.checkPage);
await figma.setCurrentPageAsync(checkPage);
for (const child of [...checkPage.children]) child.remove();
const collections = await figma.variables.getLocalVariableCollectionsAsync();
const colorCollection = collections.find((c) => c.name === 'color');
const typeCollection = collections.find((c) => c.name === 'typography');

const frames = [];
let y = 0;
for (const [mode, background] of [['Light surface', 'color/background'], ['Dark surface', 'color/surface-dark']]) {
  const frame = figma.createAutoLayout('VERTICAL', { name: mode, itemSpacing: 16, paddingTop: 40, paddingBottom: 40, paddingLeft: 40, paddingRight: 40 });
  checkPage.appendChild(frame);
  frame.fills = [paint(background)];
  frame.setExplicitVariableModeForCollection(colorCollection, colorCollection.modes.find((m) => m.name === mode).modeId);
  frame.setExplicitVariableModeForCollection(typeCollection, typeCollection.modes.find((m) => m.name === 'Desktop').modeId);

  const header = figma.createAutoLayout('HORIZONTAL', { name: 'states', itemSpacing: 0 });
  frame.appendChild(header); header.fills = [];
  const cellText = async (chars, width) => {
    const t = figma.createText();
    t.fontName = { family: 'Inter', style: 'Regular' };
    t.characters = chars; t.fontSize = 12;
    t.fills = [paint('color/text-muted')];
    t.resize(width, t.height); t.textAutoResize = 'HEIGHT';
    return t;
  };
  header.appendChild(await cellText(mode, 120));
  for (const s of PLAN.states) header.appendChild(await cellText(s, 220));

  for (const row of PLAN.variants) {
    const line = figma.createAutoLayout('HORIZONTAL', { name: row.variant + ' · ' + row.size, itemSpacing: 0, counterAxisAlignItems: 'CENTER' });
    frame.appendChild(line); line.fills = [];
    line.appendChild(await cellText(row.size === 'Main' ? row.variant : row.size, 120));
    for (const s of PLAN.states) {
      const slot = figma.createFrame(); slot.name = s; slot.fills = [];
      slot.layoutMode = 'HORIZONTAL'; slot.counterAxisAlignItems = 'CENTER';
      slot.primaryAxisSizingMode = 'FIXED'; slot.counterAxisSizingMode = 'FIXED'; slot.resize(220, 72);
      line.appendChild(slot);
      const comp = set.children.find((c) => c.name === 'Variant=' + row.variant + ', Size=' + row.size + ', State=' + s);
      if (comp) slot.appendChild(comp.createInstance());
      else slot.appendChild(await cellText('n/a', 120));
    }
  }
  frame.x = 0; frame.y = y;
  y += frame.height + 80;
  frames.push({ id: frame.id, name: frame.name, width: Math.round(frame.width), height: Math.round(frame.height) });
}

return { componentSetId: set.id, variants: set.children.length, updated: ids.updated.length, created: ids.created.length,
  variantIds: set.children.map((c) => c.id).sort(), checkPageId: checkPage.id, frames };
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, script);
const count = VARIANTS.reduce((n, r) => n + STATES.filter((s) => !(r.noDisable && (s === 'Disabled' || s === 'Loading'))).length, 0);
console.log(`✔︎ ${OUT_FILE}: ${count} Button variants, roles match components/button.css.`);
